        execute immediate q'[comment on table retenciones is 'Comprobantes de retencion (IVA e ISLR): cabecera con una o varias lineas']';
        execute immediate q'[comment on column retenciones.tipo is 'IVA = comprobante de IVA; ISLR = comprobante de impuesto sobre la renta']';
        execute immediate q'[comment on column retenciones.numero_comprobante is 'AAAAMM + 8 digitos secuenciales; el AAAAMM es el mes de emision']';
        execute immediate q'[comment on column retenciones.id_compra is 'Factura de compra que origina el comprobante; nulo cuando se consoliden varias en un papel']';
        execute immediate q'[comment on column retenciones.total_con_iva_bs is 'Total del documento con IVA, en bolivares (la suma de las lineas)']';
        execute immediate q'[comment on column retenciones.sin_derecho_credito_bs is 'Compras sin derecho a credito fiscal, en bolivares; hoy siempre 0']';
        execute immediate q'[comment on column retenciones.base_imponible_bs is 'Base de las lineas con IVA mayor que cero (sin exento ni IGTF), en bolivares']';
        execute immediate q'[comment on column retenciones.impuesto_bs is 'IVA causado del documento, en bolivares']';
        execute immediate q'[comment on column retenciones.retenido_bs is 'Importe retenido en bolivares (IVA causado por el porcentaje, o ISLR ya calculado)']';
        execute immediate q'[comment on column retenciones.codigo_concepto is 'Codigo SENIAT del concepto de ISLR que imprime la cabecera del papel']';
        execute immediate q'[comment on column retenciones.estado is 'EMITIDO = vigente; ANULADO = anulado con la compra, conserva su numero']';
    end if;

    -- 3. Las lineas
    if not existe_tabla('RETENCIONES_DET') then
        execute immediate q'[
create table retenciones_det (
    id_linea               number generated by default on null as identity
                           minvalue 1 maxvalue 9999999999999999999999999999
                           increment by 1 cache 20 noorder nocycle nokeep noscale
                           not null enable,
    id_retencion           number        not null enable,
    id_compra              number        not null enable,
    fecha_factura          date,
