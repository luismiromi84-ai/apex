    v_in number;
begin
    select count(*) into v_in from all_objects
     where owner = 'WKSP_SYPEXWS' and status = 'INVALID';
    if v_in > 0 then
        raise_application_error(-20112, 'quedaron ' || v_in || ' objetos invalidos');
    end if;

    select count(*) into v_n from all_tables
     where owner = 'WKSP_SYPEXWS' and table_name in ('ISLR_CONCEPTOS','RETENCIONES','RETENCIONES_DET');
    if v_n <> 3 then
        raise_application_error(-20112, 'faltan tablas del modelo de retenciones (' || v_n || ' de 3)');
    end if;

    select count(*) into v_n from all_tab_columns
     where owner = 'WKSP_SYPEXWS' and column_name = 'ID_CONCEPTO_ISLR'
       and table_name in ('COMPRAS','PROVEEDORES');
    if v_n <> 2 then
        raise_application_error(-20112, 'falta ID_CONCEPTO_ISLR en compras o proveedores');
    end if;

    select count(*) into v_n from syn_parametros where clave = 'UT_ISLR';
    if v_n <> 1 then
        raise_application_error(-20112, 'falta UT_ISLR en SYN_PARAMETROS');
    end if;

    -- Los cuatro indices: sin esto, un corte a mitad dejaba las tablas sin indice
    -- y la validacion seguia diciendo que todo estaba bien.
    select count(*) into v_n from all_indexes
     where owner = 'WKSP_SYPEXWS'
       and index_name in ('IX_RET_EMPRESA','IX_RET_PROVEEDOR',
                          'IX_RETDET_RETENCION','IX_RETDET_COMPRA');
    if v_n <> 4 then
        raise_application_error(-20112, 'faltan indices del modelo de retenciones (' || v_n || ' de 4)');
    end if;
end;
