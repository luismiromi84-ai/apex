-- =============================================================================
-- 7. El comprobante de IVA historico: RETENCIONES_IVA -> RETENCIONES +
--    RETENCIONES_DET.
--
-- La cabecera copia los totales de RETENCIONES_IVA tal cual (base, IVA y
-- retenido): son la foto con la que se emitio el papel y no se recalculan ni se
-- renumeran. De la compra salen el proveedor, el total del documento con IVA
-- (monto_total x tasa) y los datos de la factura del proveedor.
--
-- El detalle NO se copia del comprobante (el viejo no guardaba la alicuota):
-- se arma del detalle de la compra, UNA LINEA POR ALICUOTA de IVA, que es la
-- regla del modelo nuevo. El exento y el IGTF no entran, con el mismo filtro que
-- pkg_retenciones.fn_base_imponible_bs. Si la compra no tiene ninguna linea
-- gravada (o no tiene lineas), se deja UNA linea de respaldo con los importes de
-- la cabecera y la alicuota en 0: la columna no admite nulo y no hay alicuota que
-- copiar, pero el comprobante no puede quedarse sin linea.
--
-- Idempotente: se salta el comprobante que ya este en RETENCIONES por cualquiera
-- de sus dos claves, el numero (empresa + tipo + numero) o la compra
-- (id_compra + tipo). Asi se puede correr las veces que haga falta sin duplicar.
--
-- Se hace commit POR COMPROBANTE: en esta ADB varias DML sobre tablas con
-- identity en una sola transaccion dan ORA-12839, y aqui cada comprobante
-- inserta en dos (RETENCIONES y RETENCIONES_DET) una o varias veces.
--
-- RETENCIONES_IVA NO SE TOCA: solo se lee.
-- =============================================================================
declare
    v_empresa   number;
    v_proveedor number;
    v_compra    number;
    v_fecha     date;
    v_folio     varchar2(50);
    v_control   varchar2(30);
    v_tipo_doc  varchar2(10);
    v_total_bs  number;
    v_id        number;
    v_ya_esta   number;
begin
    for r in (select * from retenciones_iva order by id_retencion) loop
        -- La FK de RETENCIONES_IVA a COMPRAS garantiza que la compra existe; si
        -- faltara, el select revienta y la migracion se detiene en vez de perder un
        -- comprobante en silencio. La empresa y el proveedor salen de la compra, que
        -- es la que manda en el modelo nuevo.
        select c.id_empresa, c.id_proveedor, c.id_compra, c.fecha_emision,
               c.folio_factura, c.nro_control, c.tipo_documento,
               round(nvl(c.monto_total, 0) * nvl(c.tipo_cambio, 1), 2)
          into v_empresa, v_proveedor, v_compra, v_fecha,
               v_folio, v_control, v_tipo_doc, v_total_bs
          from compras c
         where c.id_compra = r.id_compra;

        -- Ya copiado: el numero esta (el unico es empresa + tipo + numero) o la
        -- compra ya tiene su comprobante de IVA (unico id_compra + tipo).
        select count(*) into v_ya_esta
          from retenciones
         where tipo = 'IVA'
           and id_empresa = v_empresa
           and (numero_comprobante = r.numero_comprobante
                or id_compra = r.id_compra);

        if v_ya_esta = 0 then
            insert into retenciones (id_empresa, id_proveedor, tipo, numero_comprobante,
                                     fecha_emision, periodo_anio, periodo_mes, id_compra,
                                     total_con_iva_bs, sin_derecho_credito_bs,
                                     base_imponible_bs, impuesto_bs, retenido_bs,
                                     estado, creado_por, fecha_creacion)
            values (v_empresa, v_proveedor, 'IVA', r.numero_comprobante,
                    r.fecha_emision, r.periodo_anio, r.periodo_mes, v_compra,
                    v_total_bs, 0,
                    r.base_imponible_bs, r.iva_causado_bs, r.iva_retenido_bs,
                    r.estado, r.creado_por, r.fecha_creacion)
            returning id_retencion into v_id;

            -- Una linea por alicuota. La base y el impuesto son los de la compra
            -- (en bolivares, con la tasa de cada linea); el retenido, el porcentaje
            -- del comprobante aplicado al IVA de ESA alicuota. Se calcula sobre el
            -- impuesto sin redondear para que, con una sola alicuota, cuadre al
            -- centimo con la cabecera (que el paquete viejo redondeo asi).
            insert into retenciones_det (id_retencion, id_compra, fecha_factura,
                                         nro_factura, nro_control, tipo_documento,
                                         total_con_iva_bs, sin_derecho_credito_bs,
                                         base_imponible_bs, porcentaje, impuesto_bs,
                                         retenido_bs)
            select v_id, v_compra, v_fecha, v_folio, v_control, v_tipo_doc,
                   nvl(sum(d.subtotal_bs), 0)
                     + round(nvl(sum(d.monto_impuesto * nvl(d.tasa_cambio_aplicada, 1)), 0), 2),
                   0,
                   nvl(sum(d.subtotal_bs), 0),
                   d.porcentaje_impuesto,
                   round(nvl(sum(d.monto_impuesto * nvl(d.tasa_cambio_aplicada, 1)), 0), 2),
                   round(nvl(sum(d.monto_impuesto * nvl(d.tasa_cambio_aplicada, 1)), 0)
                         * nvl(r.porcentaje_retencion, 0) / 100, 2)
              from compras_det d
             where d.id_compra = v_compra
               and nvl(d.porcentaje_impuesto, 0) > 0
               and not exists (select 1
                                 from impuestos i
                                where i.id_impuesto = d.id_impuesto
                                  and (i.cod_impuesto = 'IGTF'
                                       or nvl(i.es_retencion, 'N') = 'S'))
             group by d.porcentaje_impuesto;

            if sql%rowcount = 0 then
                -- Compra sin lineas gravadas: una sola linea con lo que dice el
                -- comprobante. La alicuota va en 0 (la columna es NOT NULL) porque no
                -- hay ninguna en el detalle de la compra que se pueda copiar.
                insert into retenciones_det (id_retencion, id_compra, fecha_factura,
                                             nro_factura, nro_control, tipo_documento,
                                             total_con_iva_bs, sin_derecho_credito_bs,
                                             base_imponible_bs, porcentaje, impuesto_bs,
                                             retenido_bs)
                values (v_id, v_compra, v_fecha,
                        v_folio, v_control, v_tipo_doc,
                        v_total_bs, 0,
                        r.base_imponible_bs, 0, r.iva_causado_bs,
                        r.iva_retenido_bs);
            end if;

            -- Un commit por comprobante (ver la cabecera del bloque).
            commit;
        end if;
    end loop;
end;
