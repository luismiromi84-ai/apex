-- =============================================================================
-- 20261119_retenciones_iva_islr.sql
--
-- Comprobantes de retencion de IVA e ISLR: el modelo de datos.
--
-- QUE HABIA: un comprobante de IVA plano (RETENCIONES_IVA, 1:1 con la compra) y
-- nada de ISLR, que en Venezuela se retiene en casi cualquier compra de
-- servicios, arrendamiento, fletes o comisiones.
--
-- QUE HACE ESTA MIGRACION (solo estructura; el calculo y la emision vienen en
-- las tareas siguientes):
--   1. ISLR_CONCEPTOS: el catalogo oficial de conceptos (codigo, actividad,
--      base %, tarifa y sustraendo en UT). Se siembra en otra migracion.
--   2. RETENCIONES: la cabecera del comprobante, para IVA y para ISLR. Unico
--      (empresa, tipo, numero) y (compra, tipo): hoy un comprobante por factura
--      y tipo; el dia que se consoliden, la cabecera ira con ID_COMPRA nulo.
--   3. RETENCIONES_DET: las lineas (una por alicuota en IVA). Aqui vive la foto
--      del calculo (base %, tarifa, sustraendo en UT, valor de la UT y
--      sustraendo en Bs), que es lo que permite reimprimir sin recalcular.
--   4. Los cuatro indices de las dos tablas nuevas.
--   5. PROVEEDORES.ID_CONCEPTO_ISLR y COMPRAS.ID_CONCEPTO_ISLR: el concepto con
--      el que se retiene, por defecto en el proveedor y heredado en la compra.
--   6. SYN_PARAMETROS.UT_ISLR = 43 (unidad tributaria vigente, G.O. 43.140).
--   7. Copia el comprobante de IVA historico de RETENCIONES_IVA a RETENCIONES +
--      RETENCIONES_DET con el mismo numero y las mismas cifras, para que nada se
--      pierda y la tabla vieja se pueda retirar mas adelante.
--
-- RETENCIONES_IVA NO SE TOCA (ni se actualiza ni se borra): se lee para la copia y
-- queda como historico.
--
-- Idempotente: las tablas se crean solo si no existen, las columnas se agregan
-- solo si faltan, los indices se crean solo si faltan, la UT se inserta solo si
-- no esta y la copia del comprobante se salta el que ya este en RETENCIONES por
-- cualquiera de sus dos claves: el numero (empresa + tipo + numero) o la compra
-- (id_compra + tipo).
--
-- Reversa (EL ORDEN IMPORTA: primero las columnas que apuntan al catalogo y
-- despues las tablas; al reves, el drop de islr_conceptos falla con ORA-02449
-- porque compras y proveedores todavia tienen su FK habilitada):
--   alter table compras drop column id_concepto_islr;
--   alter table proveedores drop column id_concepto_islr;
--   drop table retenciones_det;   -- se lleva las lineas copiadas
--   drop table retenciones;       -- se lleva la cabecera copiada
--   drop table islr_conceptos;
--   delete from syn_parametros where clave = 'UT_ISLR';
--   (el historico del IVA sigue intacto en RETENCIONES_IVA: la copia solo lee)
--
-- Verificacion: deploy/diagnostico/20261119_retenciones_verificacion.sql
-- =============================================================================

