        execute immediate q'[comment on column retenciones_det.sustraendo_ut is 'Sustraendo en unidades tributarias con el que se calculo (foto del concepto)']';
        execute immediate q'[comment on column retenciones_det.valor_ut is 'Valor de la unidad tributaria en bolivares al emitir']';
        execute immediate q'[comment on column retenciones_det.sustraendo_bs is 'Sustraendo llevado a bolivares (sustraendo en UT por el valor de la UT)']';
    end if;

    -- 4. Los indices. VAN FUERA del bloque de creacion a proposito: el DDL hace
    -- commit, asi que un corte entre el create table y el create index dejaria la
    -- tabla sin indice y el re-run no volveria a entrar en la rama. Se guardan por
    -- all_indexes, como las columnas por all_tab_columns.
    select count(*) into v_n from all_indexes
     where owner = 'WKSP_SYPEXWS' and index_name = 'IX_RET_EMPRESA';
    if v_n = 0 then
        execute immediate 'create index ix_ret_empresa on retenciones (id_empresa)';
    end if;

    select count(*) into v_n from all_indexes
     where owner = 'WKSP_SYPEXWS' and index_name = 'IX_RET_PROVEEDOR';
    if v_n = 0 then
        execute immediate 'create index ix_ret_proveedor on retenciones (id_proveedor)';
    end if;

    select count(*) into v_n from all_indexes
     where owner = 'WKSP_SYPEXWS' and index_name = 'IX_RETDET_RETENCION';
    if v_n = 0 then
        execute immediate 'create index ix_retdet_retencion on retenciones_det (id_retencion)';
    end if;

    -- La FK a la compra tambien se indexa: el repo indexa sus otras FK al padre
    -- (ix_compras_origen, ix_fact_det_origen) y sin indice el borrado del padre
    -- bloquea la tabla entera.
    select count(*) into v_n from all_indexes
     where owner = 'WKSP_SYPEXWS' and index_name = 'IX_RETDET_COMPRA';
    if v_n = 0 then
        execute immediate 'create index ix_retdet_compra on retenciones_det (id_compra)';
    end if;

    -- 5. El concepto de ISLR en el proveedor y en la compra
    select count(*) into v_n from all_tab_columns
     where owner = 'WKSP_SYPEXWS' and table_name = 'PROVEEDORES' and column_name = 'ID_CONCEPTO_ISLR';
    if v_n = 0 then
        execute immediate 'alter table proveedores add (id_concepto_islr number)';
    end if;

    select count(*) into v_n from all_constraints
     where owner = 'WKSP_SYPEXWS' and table_name = 'PROVEEDORES'
       and constraint_name = 'FK_PROVEEDORES_ISLR';
    if v_n = 0 then
        execute immediate 'alter table proveedores add constraint fk_proveedores_islr '
                       || 'foreign key (id_concepto_islr) references islr_conceptos (id_concepto)';
    end if;
    execute immediate q'[comment on column proveedores.id_concepto_islr is 'Concepto de ISLR con el que se retiene por defecto; nulo = no se le retiene ISLR']';

    select count(*) into v_n from all_tab_columns
     where owner = 'WKSP_SYPEXWS' and table_name = 'COMPRAS' and column_name = 'ID_CONCEPTO_ISLR';
    if v_n = 0 then
        execute immediate 'alter table compras add (id_concepto_islr number)';
    end if;

    select count(*) into v_n from all_constraints
     where owner = 'WKSP_SYPEXWS' and table_name = 'COMPRAS'
       and constraint_name = 'FK_COMPRAS_ISLR';
    if v_n = 0 then
        execute immediate 'alter table compras add constraint fk_compras_islr '
                       || 'foreign key (id_concepto_islr) references islr_conceptos (id_concepto)';
    end if;
    execute immediate q'[comment on column compras.id_concepto_islr is 'Concepto de ISLR con el que se retiene esta compra; heredado del proveedor y editable en BORRADOR; nulo = no se retiene ISLR']';

    -- 6. La unidad tributaria, parametrizable (el dueño la fija en 43,00 Bs)
    select count(*) into v_n from syn_parametros where clave = 'UT_ISLR';
    if v_n = 0 then
        insert into syn_parametros (clave, valor, descripcion)
        values ('UT_ISLR', 43, 'Unidad Tributaria del ISLR en bolivares (43,00 desde 2025, G.O. 43.140)');
    end if;

    commit;
end;
