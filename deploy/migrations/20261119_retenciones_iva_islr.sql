declare
    v_n number;

    function existe_tabla(p_tabla varchar2) return boolean is
        v number;
    begin
        select count(*) into v from all_tables
         where owner = 'WKSP_SYPEXWS' and table_name = p_tabla;
        return v > 0;
    end;
begin
    -- 1. El catalogo de conceptos de ISLR
    if not existe_tabla('ISLR_CONCEPTOS') then
        execute immediate q'[
create table islr_conceptos (
    id_concepto   number generated by default on null as identity
                  minvalue 1 maxvalue 9999999999999999999999999999
                  increment by 1 cache 20 noorder nocycle nokeep noscale
                  not null enable,
    codigo        varchar2(5)   not null enable,
    numeral       varchar2(10),
    descripcion   varchar2(200) not null enable,
    actividad     varchar2(200) not null enable,
    base_pct      number(5,2)   default 100 not null enable,
    tarifa        number(5,2)   not null enable,
    sustraendo_ut number(10,4)  default 0 not null enable,
    tipo_persona  char(1),
    domiciliado   char(1),
    activo        char(1)       default 'S' not null enable,
    constraint pk_islr_conceptos primary key (id_concepto)
        using index enable,
    constraint uq_islr_conceptos_codigo unique (codigo)
        using index enable,
    constraint chk_islr_activo check (activo in ('S','N')) enable,
    constraint chk_islr_persona check (tipo_persona in ('J','N')) enable,
    constraint chk_islr_domicilio check (domiciliado in ('S','N')) enable,
    constraint chk_islr_base check (base_pct between 0 and 100) enable,
    constraint chk_islr_tarifa check (tarifa between 0 and 100) enable
)]';
        execute immediate q'[comment on table islr_conceptos is 'Conceptos de retencion de ISLR de la tabla oficial del SENIAT (Decreto 1.808); una fila por codigo']';
        execute immediate q'[comment on column islr_conceptos.codigo is 'Codigo SENIAT del concepto (002, 053, 057...); es la llave del catalogo']';
        execute immediate q'[comment on column islr_conceptos.numeral is 'Numeral del articulo 9 del reglamento; informativo']';
        execute immediate q'[comment on column islr_conceptos.actividad is 'Descripcion de la actividad que imprime el comprobante']';
        execute immediate q'[comment on column islr_conceptos.base_pct is 'Porcentaje del monto del documento que queda sujeto a retencion (100, 90, 30...)']';
        execute immediate q'[comment on column islr_conceptos.tarifa is 'Porcentaje de retencion sobre la base']';
        execute immediate q'[comment on column islr_conceptos.sustraendo_ut is 'Sustraendo expresado en unidades tributarias, con 4 decimales (2,5 para el 3 %; 0,8333 para el 1 %)']';
        execute immediate q'[comment on column islr_conceptos.activo is 'S = se puede elegir en la compra; N = solo informativo (tarifa progresiva o formula especial)']';
    end if;

    -- 2. La cabecera del comprobante
    if not existe_tabla('RETENCIONES') then
        execute immediate q'[
create table retenciones (
    id_retencion           number generated by default on null as identity
                           minvalue 1 maxvalue 9999999999999999999999999999
