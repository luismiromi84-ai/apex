alter session set current_schema = WKSP_SYPEXWS;
/

-- -----------------------------------------------------------------------------
-- 0. Que hay ahora (deja constancia de lo que se va a borrar)
-- -----------------------------------------------------------------------------
select 'presupuestos' as tabla, count(*) as filas from presupuestos where id_presupuesto between 1000 and 1999
union all
select 'facturas', count(*) from facturas where id_factura between 1000 and 1999
union all
select 'clientes', count(*) from clientes where id_cliente between 1000 and 1999
union all
select 'productos', count(*) from producto_servicio where id_producto_servicio between 1000 and 1999
union all
select 'tipos de cambio', count(*) from tipo_cambio where id_tipo_cambio between 1000 and 1999
union all
select 'usuarios de prueba', count(*) from usuario where usuario_id between 1000 and 1999
                           or usuario_id between 9000 and 9999;
/

-- -----------------------------------------------------------------------------
-- 1. Borrado, en orden inverso a las FK
-- -----------------------------------------------------------------------------
delete from facturas_det        where id_detalle           between 1000 and 1999;
/

delete from facturas            where id_factura           between 1000 and 1999;
/

delete from presupuestos_det    where id_detalle           between 1000 and 1999;
/

delete from presupuestos        where id_presupuesto       between 1000 and 1999;
/

delete from tipo_cambio         where id_tipo_cambio       between 1000 and 1999;
/

delete from producto_servicio   where id_producto_servicio between 1000 and 1999;
/

delete from clientes            where id_cliente           between 1000 and 1999;
/

delete from usuario             where usuario_id           between 1000 and 1999;
/

delete from usuario             where usuario_id           between 9000 and 9999;
/

delete from syn_roles           where id_rol               between 1000 and 1999;
/

commit;
/

-- -----------------------------------------------------------------------------
-- 2. Realinear las secuencias identity de lo que quedo vacio
--    (si no, el primer registro real nace en 1046)
--    START WITH LIMIT VALUE toma max(columna)+1; con la tabla vacia queda en 1.
-- -----------------------------------------------------------------------------
alter table presupuestos     modify (id_presupuesto       generated by default as identity (start with limit value));
/

alter table presupuestos_det modify (id_detalle           generated by default as identity (start with limit value));
/

alter table facturas         modify (id_factura           generated by default as identity (start with limit value));
/

alter table facturas_det     modify (id_detalle           generated by default as identity (start with limit value));
/

alter table clientes         modify (id_cliente           generated by default as identity (start with limit value));
/

alter table producto_servicio modify (id_producto_servicio generated by default as identity (start with limit value));
/

alter table tipo_cambio      modify (id_tipo_cambio       generated by default as identity (start with limit value));
/

alter table usuario          modify (usuario_id           generated by default as identity (start with limit value));
/

alter table syn_roles        modify (id_rol               generated by default as identity (start with limit value));
/

-- -----------------------------------------------------------------------------
-- 3. Validacion: todo lo demo debe estar en cero
-- -----------------------------------------------------------------------------
select 'FALLA: quedan presupuestos demo' as caso from dual
 where exists (select 1 from presupuestos where id_presupuesto between 1000 and 1999);
/

select 'FALLA: quedan facturas demo' as caso from dual
 where exists (select 1 from facturas where id_factura between 1000 and 1999);
/

select 'FALLA: quedan usuarios de prueba' as caso from dual
 where exists (select 1 from usuario where usuario_id between 1000 and 1999 or usuario_id between 9000 and 9999);
/

select 'Queda como real: ' || username as aviso from usuario order by usuario_id;
/
