-- 1. Quita la responsabilidad del COMMIT al procedimiento (ya hecho) y la pone
--    en un wrapper que sí es dueño de la transacción del job.
-- 2. Agrega la tasa MXN -> VES. La API de BCV no publica MXN, así que:
--      a) si la API trae la clave MXN, se usa;
--      b) si no, se calcula con el parámetro USD_MXN (pesos por dólar);
--      c) si no hay ninguna, se registra y se omite (el job no falla).
-- 3. Crea JOB_ACTUALIZA_TASAS_BCV: diario 18:00 America/Caracas, 3 intentos.
-- =============================================================================

alter session set current_schema = WKSP_SYPEXWS;

-- ---------------------------------------------------------------------------
-- Parámetros y bitácora
-- ---------------------------------------------------------------------------
create table syn_parametros (
    clave       varchar2(50) constraint pk_syn_parametros primary key,
    valor       number,
    descripcion varchar2(200)
);

insert into syn_parametros (clave, valor, descripcion)
values ('USD_MXN', null, 'Pesos mexicanos por dolar. Se usa para derivar MXN->VES si la API no trae MXN');

create table log_tasas_bcv (
    id           number generated by default as identity constraint pk_log_tasas_bcv primary key,
    ejecutado_el timestamp default systimestamp,
    origen       varchar2(20),
    resultado    varchar2(10),
    monedas      varchar2(200),
    mensaje      varchar2(400)
);

-- ---------------------------------------------------------------------------
-- Procedimiento principal: USD, EUR y MXN. SIN commit.
-- ---------------------------------------------------------------------------
create or replace procedure prc_actualizar_tasas_diarias is
    v_response       clob;
    v_tasa_usd       number;
    v_tasa_eur       number;
    v_tasa_mxn       number;
    v_usd_mxn        number;
    v_effective_date varchar2(10);
    v_fecha_vigencia date;
begin
    v_response := apex_web_service.make_rest_request(
        p_url         => 'https://bcv.today/api/v1/rate.json',
        p_http_method => 'GET'
    );

    apex_json.parse(v_response);

    v_tasa_usd       := apex_json.get_number(p_path => 'USD');
    v_tasa_eur       := apex_json.get_number(p_path => 'EUR');
    v_effective_date := apex_json.get_varchar2(p_path => 'effective_date');
    v_fecha_vigencia := to_date(v_effective_date, 'YYYY-MM-DD');

    -- MXN: primero la API, si no el parámetro USD_MXN
    if apex_json.does_exist(p_path => 'MXN') then
        v_tasa_mxn := apex_json.get_number(p_path => 'MXN');
    else
        begin
            select valor into v_usd_mxn from syn_parametros where clave = 'USD_MXN';
        exception
            when no_data_found then v_usd_mxn := null;
        end;
        if v_usd_mxn is not null and v_usd_mxn > 0 then
            v_tasa_mxn := v_tasa_usd / v_usd_mxn;
        end if;
    end if;

    merge into tipo_cambio target
    using (select 'USD' as moneda_origen, 'VES' as moneda_destino, 'REAL' as tipo_tasa,
                  v_tasa_usd as tasa_cambio, v_fecha_vigencia as fecha_vigencia
             from dual) src
       on (target.moneda_origen = src.moneda_origen
           and target.moneda_destino = src.moneda_destino
           and target.tipo_tasa = src.tipo_tasa
           and target.fecha_vigencia = src.fecha_vigencia)
     when matched then update set target.tasa_cambio = src.tasa_cambio
     when not matched then
        insert (moneda_origen, moneda_destino, tipo_tasa, tasa_cambio, fecha_vigencia)
        values (src.moneda_origen, src.moneda_destino, src.tipo_tasa, src.tasa_cambio, src.fecha_vigencia);

    merge into tipo_cambio target
    using (select 'EUR' as moneda_origen, 'VES' as moneda_destino, 'REAL' as tipo_tasa,
                  v_tasa_eur as tasa_cambio, v_fecha_vigencia as fecha_vigencia
             from dual) src
       on (target.moneda_origen = src.moneda_origen
           and target.moneda_destino = src.moneda_destino
           and target.tipo_tasa = src.tipo_tasa
           and target.fecha_vigencia = src.fecha_vigencia)
     when matched then update set target.tasa_cambio = src.tasa_cambio
     when not matched then
        insert (moneda_origen, moneda_destino, tipo_tasa, tasa_cambio, fecha_vigencia)
        values (src.moneda_origen, src.moneda_destino, src.tipo_tasa, src.tasa_cambio, src.fecha_vigencia);

    if v_tasa_mxn is not null then
        merge into tipo_cambio target
        using (select 'MXN' as moneda_origen, 'VES' as moneda_destino, 'REAL' as tipo_tasa,
                      round(v_tasa_mxn, 6) as tasa_cambio, v_fecha_vigencia as fecha_vigencia
                 from dual) src
           on (target.moneda_origen = src.moneda_origen
               and target.moneda_destino = src.moneda_destino
               and target.tipo_tasa = src.tipo_tasa
               and target.fecha_vigencia = src.fecha_vigencia)
         when matched then update set target.tasa_cambio = src.tasa_cambio
         when not matched then
            insert (moneda_origen, moneda_destino, tipo_tasa, tasa_cambio, fecha_vigencia)
            values (src.moneda_origen, src.moneda_destino, src.tipo_tasa, src.tasa_cambio, src.fecha_vigencia);
    end if;
end prc_actualizar_tasas_diarias;
/

-- ---------------------------------------------------------------------------
-- Wrapper del job: dueño de la transacción y de los reintentos.
-- ---------------------------------------------------------------------------
create or replace procedure prc_job_tasas_bcv is
    c_intentos constant number := 3;
    v_error    varchar2(400);
begin
    for i in 1 .. c_intentos loop
        begin
            prc_actualizar_tasas_diarias;
            commit;
            insert into log_tasas_bcv (origen, resultado, monedas, mensaje)
            values ('JOB', 'OK', 'USD, EUR, MXN', 'intento ' || i || ' correcto');
            commit;
            return;
        exception
            when others then
                rollback;
                v_error := substr(sqlerrm, 1, 400);
                insert into log_tasas_bcv (origen, resultado, monedas, mensaje)
                values ('JOB', 'REINTENTO', null, 'intento ' || i || ': ' || v_error);
                commit;
        end;
    end loop;

    insert into log_tasas_bcv (origen, resultado, mensaje)
    values ('JOB', 'ERROR', 'agotados ' || c_intentos || ' intentos: ' || v_error);
    commit;
end prc_job_tasas_bcv;
/

-- ---------------------------------------------------------------------------
-- Job: diario 18:00 America/Caracas, 3 intentos (dentro del wrapper).
-- Se crea deshabilitado hasta validar una ejecución manual.
-- ---------------------------------------------------------------------------
begin
    dbms_scheduler.drop_job('JOB_ACTUALIZA_TASAS_BCV', force => true);
exception
    when others then null;
end;
/

begin
    dbms_scheduler.create_job(
        job_name        => 'JOB_ACTUALIZA_TASAS_BCV',
        job_type        => 'STORED_PROCEDURE',
        job_action      => 'PRC_JOB_TASAS_BCV',
        start_date      => systimestamp at time zone 'America/Caracas',
        repeat_interval => 'FREQ=DAILY;BYHOUR=18;BYMINUTE=0;BYSECOND=0;BYTIMEZONE=America/Caracas',
        enabled         => false,
        comments        => 'Tasas BCV (USD, EUR, MXN) diarias a las 18:00 de Caracas, 3 intentos'
    );
end;
/

commit;

select 'parametros' as control, count(*) as filas from syn_parametros
union all select 'log', count(*) from log_tasas_bcv
union all select 'job', count(*) from user_scheduler_jobs where job_name = 'JOB_ACTUALIZA_TASAS_BCV';

