-- 20261106_monitoreo_errores.sql
--
-- Objetivo: enterarse de los fallos de la aplicacion. Hasta hoy un error en
--           produccion solo se veia si el usuario lo contaba; APEX lo deja en
--           APEX_WORKSPACE_ACTIVITY_LOG, pero esa vista se recorta y solo se
--           mira por SQL.
--
-- Que hace:
--   1. Crea SYN_ERROR_LOG (una fila por error: usuario, pagina, codigo,
--      mensaje, sentencia, tipo).
--   2. Crea PRC_LOG_ERROR, que escribe en transaccion autonoma y nunca lanza.
--   3. Crea FN_ERROR_HANDLER, el manejador de errores de la app: registra y
--      devuelve el mismo mensaje de siempre, asi que el usuario no nota nada.
--   4. Amplia PRC_PURGAR_LOGS para que tambien recorte SYN_ERROR_LOG con la
--      misma retencion (90 dias por defecto).
--
-- Ademas hay que decirle a APEX que use el manejador: el export trae
--   ,p_error_handling_function=>'fn_error_handler'
-- en el create_flow. Este script NO cambia la aplicacion.
--
-- Afecta a: tabla nueva, dos objetos nuevos y un procedimiento existente.
--           No toca datos de negocio.
--
-- Idempotente: la tabla se crea solo si no existe, los objetos se recrean y el
-- cuerpo de PRC_PURGAR_LOGS se vuelve a compilar.
--
-- Ejecutar:
--   python deploy/conexion/importar_export.py deploy/migrations/20261106_monitoreo_errores.sql
--
-- Verificacion:
--   deploy/diagnostico/20261106_monitoreo_errores_verificacion.sql
--
-- REVERSA:
--   begin execute immediate 'drop table syn_error_log purge'; end;
--   drop function fn_error_handler;
--   drop procedure prc_log_error;
--   -- y volver a compilar el prc_purgar_logs de deploy/migrations/20261105_purgar_logs.sql
--   -- quitando del export el p_error_handling_function
-- =============================================================================

alter session set current_schema = WKSP_SYPEXWS;
/

declare
    v_existe number;
begin
    select count(*) into v_existe
      from all_tables
     where owner = 'WKSP_SYPEXWS' and table_name = 'SYN_ERROR_LOG';

    if v_existe = 0 then
        execute immediate q'~
            create table syn_error_log (
                id_error      number generated by default as identity
                              constraint pk_syn_error_log primary key,
                fecha         date default sysdate not null,
                usuario       varchar2(100),
                sesion        varchar2(50),
                id_aplicacion number,
                id_pagina     number,
                peticion      varchar2(400),
                componente    varchar2(300),
                codigo        varchar2(30),
                mensaje       varchar2(4000),
                detalle       varchar2(4000),
                sentencia     varchar2(4000),
                es_interno    varchar2(1)
            )~';
        execute immediate
            'create index ix_syn_error_log_fecha on syn_error_log (fecha)';
    end if;
end;
/

create or replace procedure prc_log_error (
    p_usuario       in varchar2,
    p_codigo        in varchar2,
    p_mensaje       in varchar2,
    p_detalle       in varchar2 default null,
    p_sentencia     in varchar2 default null,
    p_componente    in varchar2 default null,
    p_peticion      in varchar2 default null,
    p_id_aplicacion in number   default null,
    p_id_pagina     in number   default null,
    p_sesion        in varchar2 default null,
    p_es_interno    in varchar2 default null
) is
    pragma autonomous_transaction;
begin
    insert into syn_error_log (
        usuario, sesion, id_aplicacion, id_pagina, peticion, componente,
        codigo, mensaje, detalle, sentencia, es_interno
    ) values (
        substr(p_usuario, 1, 100),
        substr(p_sesion, 1, 50),
        p_id_aplicacion,
        p_id_pagina,
        substr(p_peticion, 1, 400),
        substr(p_componente, 1, 300),
        substr(p_codigo, 1, 30),
        substr(p_mensaje, 1, 4000),
        substr(p_detalle, 1, 4000),
        substr(p_sentencia, 1, 4000),
        substr(p_es_interno, 1, 1)
    );
    commit;
exception
    when others then
        rollback;
end prc_log_error;
/

create or replace function fn_error_handler (
    p_error in apex_error.t_error
) return apex_error.t_error_result
is
    l_result  apex_error.t_error_result;
    l_mensaje varchar2(4000);
    l_codigo  varchar2(30);
begin
    l_mensaje := apex_error.get_first_ora_error_text(p_error => p_error);
    if l_mensaje is null then
        l_mensaje := p_error.message;
    end if;

    l_result := apex_error.t_error_result();
    l_result.message          := l_mensaje;
    l_result.additional_info  := p_error.additional_info;
    l_result.display_location := p_error.display_location;

    if p_error.ora_sqlcode is not null then
        l_codigo := 'ORA-' || lpad(to_char(abs(p_error.ora_sqlcode)), 5, '0');
    end if;

    begin
        prc_log_error(
            p_usuario       => apex_application.g_user,
            p_codigo        => l_codigo,
            p_mensaje       => nvl(l_mensaje, p_error.message),
            p_detalle       => p_error.ora_sqlerrm,
            p_sentencia     => p_error.error_statement,
            p_componente    => p_error.page_item_name,
            p_peticion      => apex_application.g_request,
            p_id_aplicacion => apex_application.g_flow_id,
            p_id_pagina     => apex_application.g_flow_step_id,
            p_sesion        => apex_application.g_instance,
            p_es_interno    => case when p_error.is_internal_error then 'S' else 'N' end
        );
    exception
        when others then
            null;
    end;

    return l_result;
end fn_error_handler;
/

grant execute on prc_log_error to public;
/

grant execute on fn_error_handler to public;
/

create or replace procedure prc_purgar_logs (
    p_dias            in  number  default 90,
    p_borrados_login  out number,
    p_borrados_reset  out number
) is
begin
    if p_dias is null or p_dias < 1 then
        raise_application_error(-20030,
            'La retencion debe ser de al menos 1 dia.');
    end if;

    delete from syn_login_log
     where fecha < sysdate - p_dias;
    p_borrados_login := sql%rowcount;

    delete from syn_reset_password_log
     where fecha < sysdate - p_dias;
    p_borrados_reset := sql%rowcount;

    -- Errores de la aplicacion: misma retencion. No se devuelve el conteo para
    -- no cambiar la firma (el job ya declara dos variables).
    delete from syn_error_log
     where fecha < sysdate - p_dias;
end prc_purgar_logs;
/

declare
    v_errores number;
begin
    dbms_utility.compile_schema('WKSP_SYPEXWS', false);

    select count(*) into v_errores
      from all_objects
     where owner = 'WKSP_SYPEXWS' and status <> 'VALID'
       and object_type in ('FUNCTION', 'PROCEDURE', 'PACKAGE', 'PACKAGE BODY',
                           'TRIGGER', 'VIEW');

    if v_errores > 0 then
        raise_application_error(-20100, 'Quedaron ' || v_errores
            || ' objetos INVALID despues de la migracion.');
    end if;
end;
/
