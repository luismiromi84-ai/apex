-- 20261104_reset_password.sql
--
-- Objetos de soporte para "Recuperar contrasena" (pagina 14):
--   - tabla SYN_RESET_PASSWORD_LOG (auditoria de intentos)
--   - procedimiento PRC_LOG_RESET_PASSWORD (transaccion autonoma)
--
-- Idempotente: crea la tabla solo si no existe (revisando USER_TABLES) y usa
-- CREATE OR REPLACE para el procedimiento. Se puede ejecutar dos veces.
-- =============================================================================

alter session set current_schema = WKSP_SYPEXWS;

declare
    v_existe number;
begin
    select count(*) into v_existe
      from all_tables
     where owner = 'WKSP_SYPEXWS'
       and table_name = 'SYN_RESET_PASSWORD_LOG';

    if v_existe = 0 then
        execute immediate q'[
create table syn_reset_password_log (
    id                number generated by default as identity,
    usuario_intentado varchar2(100) not null,
    correo_intentado  varchar2(255) not null,
    ip                varchar2(64),
    fecha             date default sysdate not null,
    resultado         varchar2(10) not null,
    constraint pk_reset_password_log primary key (id),
    constraint ck_reset_password_log_res check (resultado in ('OK', 'FALLO'))
)]';
        execute immediate 'create index idx_reset_password_log_fecha on syn_reset_password_log (fecha)';
    end if;
end;
/

create or replace procedure prc_log_reset_password (
    p_usuario   in varchar2,
    p_correo    in varchar2,
    p_ip        in varchar2 default null,
    p_resultado in varchar2
) is
    pragma autonomous_transaction;
begin
    insert into syn_reset_password_log (
        usuario_intentado, correo_intentado, ip, fecha, resultado
    ) values (
        substr(p_usuario, 1, 100),
        substr(p_correo, 1, 255),
        substr(p_ip, 1, 64),
        sysdate,
        p_resultado
    );
    commit;
exception
    when others then
        rollback;
end prc_log_reset_password;
/

select table_name, status
  from all_tables
 where owner = 'WKSP_SYPEXWS'
   and table_name = 'SYN_RESET_PASSWORD_LOG';

select object_name, object_type, status
  from all_objects
 where owner = 'WKSP_SYPEXWS'
   and object_name = 'PRC_LOG_RESET_PASSWORD';

