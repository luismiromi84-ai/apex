-- -----------------------------------------------------------------------------
-- 2. Registro de intentos en transaccion autonoma
--
-- APEX descarta el DML de una autenticacion fallida, asi que el contador y el
-- bloqueo tienen que guardarse fuera de esa transaccion o nunca subirian.
-- -----------------------------------------------------------------------------
create or replace procedure prc_auth_registrar (
    p_usuario_id        in number,
    p_resultado         in varchar2,
    p_usuario_intentado in varchar2,
    p_nuevo_hash        in varchar2 default null
) is
    pragma autonomous_transaction;
    c_max_intentos    constant number := 5;
    c_minutos_bloqueo constant number := 15;
    v_reintentos      number;
    v_bloqueado       date;
    v_ip              varchar2(64);
begin
    begin
        v_ip := substr(owa_util.get_cgi_env('REMOTE_ADDR'), 1, 64);
    exception
        when others then
            v_ip := null;  -- fuera de una peticion web no hay CGI env
    end;

    if p_usuario_id is not null then
        begin
            select nvl(reintentos_fallidos, 0), bloqueado_hasta
              into v_reintentos, v_bloqueado
              from usuario
             where usuario_id = p_usuario_id
               for update;

            if p_resultado = 'OK' then
                update usuario set
                       reintentos_fallidos  = 0,
                       bloqueado_hasta      = null,
                       ultimo_intento_login = sysdate,
                       password_hash        = nvl(p_nuevo_hash, password_hash)
                 where usuario_id = p_usuario_id;
            elsif p_resultado = 'CLAVE_MALA' then
                v_reintentos := v_reintentos + 1;
                update usuario set
                       reintentos_fallidos  = v_reintentos,
                       bloqueado_hasta      = case
                           when v_bloqueado is not null then v_bloqueado
                           when v_reintentos >= c_max_intentos
                               then sysdate + c_minutos_bloqueo / 1440
                           else null
                       end,
                       ultimo_intento_login = sysdate
                 where usuario_id = p_usuario_id;
            else
                -- INACTIVO, BLOQUEADO, SIN_EMPRESA, ERROR: se registra el intento
                -- pero no cuentan como fallo de contrasena ni mueven el bloqueo
                update usuario set
                       ultimo_intento_login = sysdate
                 where usuario_id = p_usuario_id;
            end if;
        exception
            when no_data_found then
                null;  -- el usuario desaparecio entre autenticar y registrar
        end;
    end if;

    insert into syn_login_log (usuario_intentado, ip, fecha, resultado)
    values (substr(p_usuario_intentado, 1, 100),
            v_ip,
            sysdate,
            p_resultado);

    commit;
end prc_auth_registrar;
/

-- -----------------------------------------------------------------------------
-- 3. Hash de contrasena (PBKDF2-HMAC-SHA256, sal por usuario)
-- -----------------------------------------------------------------------------

create or replace function sypex_hash_password (
    p_password in varchar2
) return varchar2 is
    c_iteraciones constant number := 100000;
    c_bloque      constant raw(4) := hextoraw('00000001');
    v_sal  raw(16);
    v_u    raw(32);
    v_xor  raw(32);
    v_key  raw(2000);
begin
    if p_password is null then
        return null;
    end if;

    v_sal := dbms_crypto.randombytes(16);
    v_key := utl_raw.cast_to_raw(p_password);

    -- PBKDF2, un solo bloque de salida (dkLen = 32 bytes)
    v_u   := dbms_crypto.mac(v_sal || c_bloque, dbms_crypto.hmac_sh256, v_key);
    v_xor := v_u;
    for i in 2 .. c_iteraciones loop
        v_u   := dbms_crypto.mac(v_u, dbms_crypto.hmac_sh256, v_key);
        v_xor := utl_raw.bit_xor(v_xor, v_u);
    end loop;

    return 'PBKDF2-SHA256$' || c_iteraciones || '$' || rawtohex(v_sal) || '$' || rawtohex(v_xor);
end sypex_hash_password;
/

create or replace function fn_verificar_password (
    p_password in varchar2,
    p_hash     in varchar2
) return boolean is
    v_iter number;
    v_sal  raw(2000);
    v_hash raw(2000);
    v_u    raw(32);
    v_xor  raw(32);
    v_key  raw(2000);
    v_leg  varchar2(64);
    v_p1   pls_integer;
    v_p2   pls_integer;
    v_p3   pls_integer;
begin
    if p_password is null or p_hash is null then
        return false;
    end if;

    if p_hash not like 'PBKDF2-SHA256$%' then
        -- formato legado
        execute immediate 'select lower(rawtohex(standard_hash(:1,''SHA256''))) from dual'
            into v_leg using p_password || 'SYPEX_SALT_2026';
        return lower(p_hash) = v_leg;
    end if;

    v_p1 := instr(p_hash, '$', 1, 1);
    v_p2 := instr(p_hash, '$', 1, 2);
    v_p3 := instr(p_hash, '$', 1, 3);

    v_iter := to_number(substr(p_hash, v_p1 + 1, v_p2 - v_p1 - 1));
    v_sal  := hextoraw(substr(p_hash, v_p2 + 1, v_p3 - v_p2 - 1));
    v_hash := hextoraw(substr(p_hash, v_p3 + 1));

    if v_iter is null or v_iter < 1 or v_sal is null or v_hash is null then
        return false;
    end if;

    v_key := utl_raw.cast_to_raw(p_password);
    v_u   := dbms_crypto.mac(v_sal || hextoraw('00000001'), dbms_crypto.hmac_sh256, v_key);
    v_xor := v_u;
    for i in 2 .. v_iter loop
        v_u   := dbms_crypto.mac(v_u, dbms_crypto.hmac_sh256, v_key);
        v_xor := utl_raw.bit_xor(v_xor, v_u);
    end loop;

    return v_xor = v_hash;
exception
    when others then
        return false;
end fn_verificar_password;
/

create or replace function fn_password_es_legado (
    p_hash in varchar2
) return boolean is
begin
    return p_hash is not null and p_hash not like 'PBKDF2-SHA256$%';
end fn_password_es_legado;
/

-- -----------------------------------------------------------------------------
-- 4. Autenticacion
-- -----------------------------------------------------------------------------

create or replace function fn_autenticar_usuario (
    p_username in varchar2,
    p_password in varchar2
) return boolean is
    v_usuario varchar2(50);
    v_id      number;
    v_hash    varchar2(512);
    v_estado  varchar2(20);
    v_bloq    date;
    v_empresa number;
    v_rol     number;
begin
    v_usuario := trim(p_username);

    if v_usuario is null or p_password is null then
        prc_auth_registrar(p_usuario_id        => null,
                           p_resultado         => 'ERROR',
                           p_usuario_intentado => nvl(v_usuario, '(vacio)'));
        apex_util.set_custom_auth_status(p_status => 'Usuario o contrase??a incorrectos.');
        return false;
    end if;

    begin
        select usuario_id, password_hash, estado, bloqueado_hasta, id_empresa, rol_id
          into v_id, v_hash, v_estado, v_bloq, v_empresa, v_rol
          from usuario
         where upper(username) = upper(v_usuario);
    exception
        when no_data_found then
            prc_auth_registrar(null, 'NO_EXISTE', v_usuario);
            apex_util.set_custom_auth_status(p_status => 'Usuario o contrase??a incorrectos.');
            return false;
        when too_many_rows then
            prc_auth_registrar(null, 'ERROR', v_usuario);
            apex_util.set_custom_auth_status(p_status => 'Usuario o contrase??a incorrectos.');
            return false;
    end;

    if upper(v_estado) not in ('ACTIVO', 'A', '1') then
        prc_auth_registrar(v_id, 'INACTIVO', v_usuario);
        apex_util.set_custom_auth_status(
            p_status => 'El usuario no est?? activo. Contacta al administrador.');
        return false;
    end if;

    if v_bloq is not null and v_bloq > sysdate then
        prc_auth_registrar(v_id, 'BLOQUEADO', v_usuario);
        apex_util.set_custom_auth_status(
            p_status => 'La cuenta est?? bloqueada temporalmente por intentos fallidos.');
        return false;
    end if;

    if v_empresa is null or v_rol is null then
        prc_auth_registrar(v_id, 'SIN_EMPRESA', v_usuario);
        apex_util.set_custom_auth_status(
            p_status => 'El usuario no tiene empresa o rol asignado. Contacta al administrador.');
        return false;
    end if;

    if not fn_verificar_password(p_password, v_hash) then
        prc_auth_registrar(v_id, 'CLAVE_MALA', v_usuario);
        apex_util.set_custom_auth_status(p_status => 'Usuario o contrase??a incorrectos.');
        return false;
    end if;

    prc_auth_registrar(
        p_usuario_id        => v_id,
        p_resultado         => 'OK',
        p_usuario_intentado => v_usuario,
        p_nuevo_hash        => case when fn_password_es_legado(v_hash)
                                    then sypex_hash_password(p_password) end);

    return true;
exception
    when others then
        begin
            prc_auth_registrar(null, 'ERROR', v_usuario);
        exception
            when others then null;
        end;
        apex_util.set_custom_auth_status(p_status => 'Error al procesar la autenticaci??n.');
        return false;
end fn_autenticar_usuario;
/

-- -----------------------------------------------------------------------------
-- 5. Post-login
-- -----------------------------------------------------------------------------

create or replace procedure prc_post_login is
    v_id_empresa     usuario.id_empresa%type;
    v_nombre_empresa empresas.nombre_empresa%type;
    v_id_rol         usuario.rol_id%type;
    v_nombre_rol     syn_roles.nombre_rol%type;
begin
    select u.id_empresa,
           e.nombre_empresa,
           u.rol_id,
           r.nombre_rol
      into v_id_empresa,
           v_nombre_empresa,
           v_id_rol,
           v_nombre_rol
      from usuario u
      join empresas e on e.id_empresa = u.id_empresa
      join syn_roles r on r.id_rol = u.rol_id
     where upper(u.username) = upper(v('APP_USER'))
       and u.estado in ('ACTIVO', 'A', '1');

    apex_util.set_session_state('F_ID_EMPRESA', v_id_empresa);
    apex_util.set_session_state('F_NOMBRE_EMPRESA', v_nombre_empresa);
    apex_util.set_session_state('F_ID_ROL', v_id_rol);
    apex_util.set_session_state('F_NOMBRE_ROL', v_nombre_rol);
exception
    when no_data_found then
        raise_application_error(-20013,
            'El usuario no tiene empresa o rol asignado. Contacta al administrador.');
end prc_post_login;
/
