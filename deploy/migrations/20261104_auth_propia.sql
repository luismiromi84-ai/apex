-- =============================================================================
-- 20261104_auth_propia.sql
--
-- Devuelve la autenticacion al esquema propio (reemplaza PRUEBA A1).
--
-- Por que: el administrador de la app debe dar de alta usuarios desde la app y
-- no debe tener acceso al App Builder. APEX prohibe crear cuentas desde una
-- aplicacion en ejecucion (APEX.API.RUNTIME_API_USAGE.ERROR en
-- CHECK_API_USE_ALLOWED) y el cliente no tiene proveedor de identidad.
-- Diseno: docs/superpowers/specs/2026-11-04-auth-propia-design.md
--
-- Orden: 1) esquema  2) hash  3) autenticacion  4) post-login  5) reversa
-- Requiere ejecutarse como ADMIN (el grant sobre SYS.DBMS_CRYPTO).
-- =============================================================================

alter session set current_schema = WKSP_SYPEXWS;
/

-- -----------------------------------------------------------------------------
-- 1. Privilegios y esquema de soporte
-- -----------------------------------------------------------------------------
grant execute on sys.dbms_crypto to wksp_sypexws;
/

alter table usuario add (reintentos_fallidos number default 0 not null);
/

alter table usuario add (bloqueado_hasta date);
/

alter table usuario add (ultimo_intento_login date);
/

create table syn_login_log (
    id                number generated by default as identity primary key,
    usuario_intentado varchar2(100),
    ip                varchar2(64),
    fecha             date default sysdate not null,
    resultado         varchar2(20) not null
);
/

create index ix_syn_login_log_fecha on syn_login_log (fecha);
/

create unique index uq_usuario_username_upper on usuario (upper(username));
/

-- -----------------------------------------------------------------------------
-- 2. Registro de intentos en transaccion autonoma
--
-- APEX descarta el DML de una autenticacion fallida, asi que el contador y el
-- bloqueo tienen que guardarse fuera de esa transaccion o nunca subirian.
-- -----------------------------------------------------------------------------
create or replace procedure prc_auth_registrar (
    p_usuario_id        in number,
    p_resultado         in varchar2,
    p_usuario_intentado in varchar2,
    p_nuevo_hash        in varchar2 default null
) is
    pragma autonomous_transaction;
    c_max_intentos    constant number := 5;
    c_minutos_bloqueo constant number := 15;
    v_reintentos      number;
    v_bloqueado       date;
    v_ip              varchar2(64);
begin
    begin
        v_ip := substr(owa_util.get_cgi_env('REMOTE_ADDR'), 1, 64);
    exception
        when others then
            v_ip := null;  -- fuera de una peticion web no hay CGI env
    end;

    if p_usuario_id is not null then
        begin
            select nvl(reintentos_fallidos, 0), bloqueado_hasta
              into v_reintentos, v_bloqueado
              from usuario
             where usuario_id = p_usuario_id
               for update;

            if p_resultado = 'OK' then
                update usuario
                   set reintentos_fallidos = 0,
                       bloqueado_hasta     = null,
                       ultimo_intento_login = sysdate,
                       password_hash       = nvl(p_nuevo_hash, password_hash)
                 where usuario_id = p_usuario_id;
            else
                v_reintentos := v_reintentos + 1;
                update usuario
                   set reintentos_fallidos = v_reintentos,
                       bloqueado_hasta = case
                           when v_bloqueado is not null then v_bloqueado
                           when v_reintentos >= c_max_intentos
                               then sysdate + c_minutos_bloqueo / 1440
                           else null
                       end,
                       ultimo_intento_login = sysdate
                 where usuario_id = p_usuario_id;
            end if;
        exception
            when no_data_found then
                null;  -- el usuario desaparecio entre autenticar y registrar
        end;
    end if;

    insert into syn_login_log (usuario_intentado, ip, fecha, resultado)
    values (substr(p_usuario_intentado, 1, 100),
            v_ip,
            sysdate,
            p_resultado);

    commit;
end prc_auth_registrar;
/
