-- Devuelve la autenticacion al esquema propio (reemplaza PRUEBA A1).
--
-- Por que: el administrador de la app debe dar de alta usuarios desde la app y
-- no debe tener acceso al App Builder. APEX prohibe crear cuentas desde una
-- aplicacion en ejecucion (APEX.API.RUNTIME_API_USAGE.ERROR en
-- CHECK_API_USE_ALLOWED) y el cliente no tiene proveedor de identidad.
-- Diseno: docs/superpowers/specs/2026-11-04-auth-propia-design.md
--
-- Orden: 1) esquema  2) hash  3) autenticacion  4) post-login  5) reversa
-- Requiere ejecutarse como ADMIN (el grant sobre SYS.DBMS_CRYPTO).
-- =============================================================================

