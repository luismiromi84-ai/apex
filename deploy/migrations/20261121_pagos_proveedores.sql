-- =============================================================================
-- 20261121_pagos_proveedores.sql
--
-- Pagos a proveedores (cuentas por pagar). Crea el modelo del diseno aprobado el
-- 2026-11-21 y deja las compras que ya existen con sus cantidades historicas.
--
--   1. Tablas PAGOS (cabecera) y PAGOS_DETALLE (aplicacion a compras).
--   2. COMPRAS gana IGTF_BS, RETENCION_ISLR_BS y FECHA_VENCIMIENTO.
--   3. CHK_COMPRAS_ESTADO admite PARCIAL y PAGADA.
--   4. Indices de consulta.
--   5. Relleno de lo ya registrado: el ISLR retenido sale del comprobante, el
--      IGTF se congela con la regla que hoy se calcula en vivo y el vencimiento
--      sale de los dias de credito del proveedor.
--   6. compile_schema y validacion de 0 objetos invalidos.
--
-- Idempotente: todo mira el diccionario antes de crear. Reversa: ver el final.
-- Verificacion: deploy/diagnostico/20261121_pagos_modelo_verificacion.sql
-- =============================================================================

alter session set current_schema = WKSP_SYPEXWS
/

-- ----------------------------------------------------------------------------
-- 1. Tablas. El DDL canonico vive en tabla/pagos.sql y tabla/pagos_detalle.sql.
-- ----------------------------------------------------------------------------
declare
    v_n number;
begin
    select count(*) into v_n
      from all_tables where owner = 'WKSP_SYPEXWS' and table_name = 'PAGOS';
    if v_n = 0 then
        execute immediate q'~
create table pagos (
    id_pago              number generated by default on null as identity
                         minvalue 1 maxvalue 9999999999999999999999999999
                         increment by 1 cache 20 noorder nocycle nokeep noscale
                         not null enable,
    id_empresa           number        not null enable,
    id_proveedor         number        not null enable,
    fecha_pago           date          default sysdate not null enable,
    cod_moneda           varchar2(3)   not null enable,
    tipo_cambio          number(14,6)  default 1 not null enable,
    monto                number(18,2)  not null enable,
    monto_bs             number(18,2)  not null enable,
    id_forma_pago        number,
    referencia           varchar2(60),
    aplica_igtf          char(1)       default 'N' not null enable,
    igtf_monto           number(18,2)  default 0 not null enable,
    igtf_bs              number(18,2)  default 0 not null enable,
    conciliado           char(1)       default 'N' not null enable,
    fecha_conciliacion   date,
    estado               varchar2(10)  default 'ACTIVO' not null enable,
    observaciones        varchar2(4000),
    creado_por           varchar2(100) default user,
    fecha_creacion       timestamp(6)  default systimestamp not null enable,
    modificado_por       varchar2(100),
    fecha_modificacion   timestamp(6),
    constraint pk_pagos primary key (id_pago) using index enable,
    constraint fk_pagos_empresa foreign key (id_empresa)
        references empresas (id_empresa) enable,
    constraint fk_pagos_proveedor foreign key (id_proveedor)
        references proveedores (id_proveedor) enable,
    constraint fk_pagos_forma_pago foreign key (id_forma_pago)
        references forma_pago (id_forma_pago) enable,
    constraint chk_pagos_estado check (estado in ('ACTIVO','ANULADO')) enable,
    constraint chk_pagos_igtf check (aplica_igtf in ('S','N')) enable,
    constraint chk_pagos_conciliado check (conciliado in ('S','N')) enable,
    constraint chk_pagos_monto check (monto > 0) enable
)~';
    end if;

    select count(*) into v_n
      from all_tables where owner = 'WKSP_SYPEXWS' and table_name = 'PAGOS_DETALLE';
    if v_n = 0 then
        execute immediate q'~
create table pagos_detalle (
    id_pago_detalle      number generated by default on null as identity
                         minvalue 1 maxvalue 9999999999999999999999999999
                         increment by 1 cache 20 noorder nocycle nokeep noscale
                         not null enable,
    id_pago              number        not null enable,
    id_compra            number        not null enable,
    monto_aplicado       number(18,2)  not null enable,
    fecha_creacion       timestamp(6)  default systimestamp not null enable,
    constraint pk_pagos_detalle primary key (id_pago_detalle) using index enable,
    constraint uq_pago_compra unique (id_pago, id_compra) using index enable,
    constraint fk_pd_pago foreign key (id_pago) references pagos (id_pago) enable,
    constraint fk_pd_compra foreign key (id_compra) references compras (id_compra) enable,
    constraint chk_pd_monto check (monto_aplicado > 0) enable
)~';
    end if;
end;
/

-- ----------------------------------------------------------------------------
-- 2. Columnas historicas en COMPRAS
-- ----------------------------------------------------------------------------
declare
    v_n number;
begin
    select count(*) into v_n from all_tab_columns
     where owner = 'WKSP_SYPEXWS' and table_name = 'COMPRAS' and column_name = 'IGTF_BS';
    if v_n = 0 then
        execute immediate 'alter table compras add (igtf_bs number(14,2) default 0 not null)';
    end if;

    select count(*) into v_n from all_tab_columns
     where owner = 'WKSP_SYPEXWS' and table_name = 'COMPRAS' and column_name = 'RETENCION_ISLR_BS';
    if v_n = 0 then
        execute immediate 'alter table compras add (retencion_islr_bs number(14,2) default 0 not null)';
    end if;

    select count(*) into v_n from all_tab_columns
     where owner = 'WKSP_SYPEXWS' and table_name = 'COMPRAS' and column_name = 'FECHA_VENCIMIENTO';
    if v_n = 0 then
        execute immediate 'alter table compras add (fecha_vencimiento date)';
    end if;
end;
/

-- ----------------------------------------------------------------------------
-- 3. El estado de la compra admite PARCIAL y PAGADA
-- ----------------------------------------------------------------------------
declare
    v_n number;
begin
    select count(*) into v_n
      from all_constraints
     where owner = 'WKSP_SYPEXWS' and constraint_name = 'CHK_COMPRAS_ESTADO'
       and instr(search_condition_vc, 'PARCIAL') > 0;
    if v_n = 0 then
        begin
            execute immediate 'alter table compras drop constraint chk_compras_estado';
        exception
            when others then
                if sqlcode <> -2443 then
                    raise;
                end if;
        end;
        execute immediate q'~alter table compras add constraint chk_compras_estado
            check (estado in ('BORRADOR','REGISTRADA','PARCIAL','PAGADA','ANULADA')) enable~';
    end if;
end;
/

-- ----------------------------------------------------------------------------
-- 4. Indices
-- ----------------------------------------------------------------------------
declare
    v_n number;
    procedure crea(p_indice varchar2, p_ddl varchar2) is
    begin
        select count(*) into v_n
          from all_indexes where owner = 'WKSP_SYPEXWS' and index_name = p_indice;
        if v_n = 0 then
            execute immediate p_ddl;
        end if;
    end;
begin
    crea('IX_PAGOS_EMPRESA', 'create index ix_pagos_empresa on pagos (id_empresa, fecha_pago)');
    crea('IX_PAGOS_PROVEEDOR', 'create index ix_pagos_proveedor on pagos (id_proveedor)');
    crea('IX_PAGOS_ESTADO', 'create index ix_pagos_estado on pagos (estado, conciliado)');
    crea('IX_PD_COMPRA', 'create index ix_pd_compra on pagos_detalle (id_compra)');
    crea('IX_COMPRAS_VENCIMIENTO',
         'create index ix_compras_vencimiento on compras (id_empresa, fecha_vencimiento)');
end;
/

-- ----------------------------------------------------------------------------
-- 5. Relleno de lo ya registrado. OJO: el "set" del update va en la misma linea
--    del "update" porque el runner descarta las lineas que empiezan por "set ".
-- ----------------------------------------------------------------------------

-- 5.1 ISLR retenido: la foto del comprobante emitido
update compras c set retencion_islr_bs = nvl((select sum(r.retenido_bs) from retenciones r where r.id_compra = c.id_compra and r.tipo = 'ISLR' and r.estado = 'EMITIDO'), 0) where exists (select 1 from retenciones r2 where r2.id_compra = c.id_compra and r2.tipo = 'ISLR' and r2.estado = 'EMITIDO')
/

-- 5.2 IGTF: se congela con la misma regla que hoy se calcula en vivo
--     (documento en divisa + empresa SPE + forma de pago que lo genera).
update compras co set igtf_bs = nvl((select case when nvl(co.cod_moneda, 'VES') not in ('VES', 'BS') and nvl(e.es_spe, 'N') = 'S' and nvl(fp.genera_igtf, 'N') = 'S' then round(round(nvl(co.monto_total, 0) * nvl(fn_alicuota_igtf(co.id_empresa), 0) / 100, 2) * nvl(co.tipo_cambio, 1), 2) else 0 end from empresas e join forma_pago fp on fp.id_forma_pago = co.id_forma_pago where e.id_empresa = co.id_empresa), 0) where co.tipo_documento = 'FAC' and co.estado <> 'ANULADA'
/

-- 5.3 Vencimiento: emision + dias de credito del proveedor
update compras co set fecha_vencimiento = co.fecha_emision + nvl((select p.dias_credito from proveedores p where p.id_proveedor = co.id_proveedor), 0) where co.fecha_vencimiento is null and co.fecha_emision is not null
/

-- ----------------------------------------------------------------------------
-- 6. Compilar y validar
-- ----------------------------------------------------------------------------
declare
    v_mal number;
begin
    dbms_utility.compile_schema('WKSP_SYPEXWS', false);

    select count(*) into v_mal
      from all_objects
     where owner = 'WKSP_SYPEXWS' and status <> 'VALID'
       and object_type in ('FUNCTION', 'PROCEDURE', 'PACKAGE', 'PACKAGE BODY', 'TRIGGER', 'VIEW');
    if v_mal > 0 then
        raise_application_error(-20100, 'quedan ' || v_mal || ' objetos invalidos');
    end if;

    -- las filas historicas no pueden quedar con la deuda inflada
    select count(*) into v_mal
      from compras c
     where c.estado <> 'ANULADA'
       and exists (select 1 from retenciones r
                    where r.id_compra = c.id_compra and r.tipo = 'ISLR' and r.estado = 'EMITIDO')
       and nvl(c.retencion_islr_bs, 0) <>
           (select nvl(sum(r2.retenido_bs), 0) from retenciones r2
             where r2.id_compra = c.id_compra and r2.tipo = 'ISLR' and r2.estado = 'EMITIDO');
    if v_mal > 0 then
        raise_application_error(-20100, v_mal || ' compras con ISLR retenido mal rellenado');
    end if;

    dbms_output.put_line('OK: modelo de pagos a proveedores creado y rellenado');
end;
