-- =============================================================================
-- 20261118_proveedores_secuencia.sql
--
-- Los id de PROVEEDORES quedaron en 87 y 88: la identidad es global y las pruebas
-- (altas y bajas de proveedores de verificacion) la consumieron. El dueño pidio
-- que la numeracion quede en secuencia (2026-11-18).
--
-- SOLO si hay huecos:
--   1. comprueba que no haya compras (renumerar cambiaria documentos emitidos);
--   2. pasa los id a negativo (una transaccion);
--   3. los pasa a 1..n en el orden original (otra transaccion);
--   4. reinicia la identidad para que el siguiente sea n+1.
--
-- OJO 1: el SET va en la misma linea del UPDATE; el runner descarta las lineas que
--        empiezan por "set ".
-- OJO 2: los dos UPDATE van en transacciones SEPARADAS (commit en medio). En esta
--        ADB, dos DML sobre las mismas filas en una transaccion dan ORA-12860
--        (deadlock de fila hermana). Si se corta entre el paso 2 y el 3, los id
--        quedan negativos y la migracion se puede volver a correr: detecta los
--        negativos y sigue por el paso 3.
--
-- Es idempotente: si max(id) = count(*), no hace nada.
-- Reversa: no aplica (los id viejos no se recuperan; estan en la copia de seguridad).
-- Verificacion: deploy/diagnostico/20261118_correlativos_verificacion.sql (P1, P2)
-- =============================================================================

alter session set current_schema = WKSP_SYPEXWS
/

-- Paso 1: ¿hay que hacer algo?
declare
    v_cnt      number;
    v_max      number;
    v_neg      number;
    v_compras  number;
begin
    select count(*), nvl(max(id_proveedor), 0),
           count(case when id_proveedor < 0 then 1 end)
      into v_cnt, v_max, v_neg from proveedores;

    if v_cnt = 0 or (v_max = v_cnt and v_neg = 0) then
        dbms_output.put_line('proveedores ya en secuencia: nada que hacer');
        return;
    end if;

    select count(*) into v_compras from compras;
    if v_compras > 0 then
        raise_application_error(-20107,
            'Hay ' || v_compras || ' compra(s): renumerar los proveedores cambiaria documentos '
            || 'ya emitidos. Revisar a mano antes de renumerar.');
    end if;
end;
/

-- Paso 2: a negativo (transaccion aparte)
declare
    v_neg number;
begin
    select count(case when id_proveedor < 0 then 1 end) into v_neg from proveedores;
    if v_neg > 0 then
        dbms_output.put_line('ya estaban en negativo: se salta este paso');
        return;
    end if;
    update proveedores set id_proveedor = -id_proveedor;
    commit;
end;
/

-- Paso 3: a 1..n en el orden original (transaccion aparte)
declare
    v_pend number;
begin
    select count(*) into v_pend from proveedores where id_proveedor < 0;
    if v_pend = 0 then
        dbms_output.put_line('no hay ids negativos: se salta este paso');
        return;
    end if;
    update proveedores p set id_proveedor = (select count(*) from proveedores q
                                              where q.id_proveedor >= p.id_proveedor);
    commit;
end;
/

-- Paso 4: la identidad continua en el maximo actual + 1
alter table proveedores modify id_proveedor generated by default on null as identity
    (start with limit value)
/

-- Paso 5: validacion
declare
    v_cnt number;
    v_max number;
    v_min number;
begin
    select count(*), max(id_proveedor), min(id_proveedor)
      into v_cnt, v_max, v_min from proveedores;
    if v_cnt > 0 and (v_max <> v_cnt or v_min <> 1) then
        raise_application_error(-20108,
            'los proveedores quedaron de ' || v_min || ' a ' || v_max || ' con ' || v_cnt || ' filas');
    end if;
end;
/

-- Paso 6: el ALTER de la identidad deja INVALIDOS los bodies que tocan PROVEEDORES
-- (pkg_compras y pkg_retenciones). Hay que recompilar el esquema y comprobar 0.
declare
    v_n number;
begin
    dbms_utility.compile_schema('WKSP_SYPEXWS', false);
    select count(*) into v_n from all_objects
     where owner = 'WKSP_SYPEXWS' and status = 'INVALID';
    if v_n > 0 then
        raise_application_error(-20109, 'quedaron ' || v_n || ' objeto(s) INVALID');
    end if;
end;
/
