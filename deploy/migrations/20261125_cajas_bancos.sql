-- Cajas y bancos (2026-11-25, pedido del dueno: «el cobro se lleva a la caja
-- principal»). Tabla CUENTAS_FONDOS por empresa, RECIBOS.ID_CUENTA (destino del
-- cobro) y PAGOS.ID_CUENTA (origen del pago). Cada empresa nace con su «Caja
-- principal» en su moneda local; los cobros y pagos que ya existian se asignan a
-- ella. fn_cuenta_fondos y los dos packages aceptan p_id_cuenta (por defecto la
-- principal). Idempotente.
