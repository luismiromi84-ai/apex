-- Una «Caja principal» por empresa, en su moneda local (USD si el pais no la tiene).
insert into cuentas_fondos (id_empresa, nombre, tipo, cod_moneda, es_principal, estado, creado_por)
select e.id_empresa, 'Caja principal', 'CAJA', nvl(pa.moneda_local, 'USD'), 'S', 'ACTIVO', 'MIGRACION'
  from empresas e
  left join paises pa on pa.cod_pais = e.cod_pais
 where not exists (select 1 from cuentas_fondos c where c.id_empresa = e.id_empresa and c.es_principal = 'S')
/

commit
/

-- Los cobros y pagos que ya existian entraron / salieron de la caja principal.
update recibos r set r.id_cuenta = (select c.id_cuenta from cuentas_fondos c
                                     where c.id_empresa = r.id_empresa and c.es_principal = 'S')
 where r.id_cuenta is null
/

commit
/

update pagos p set p.id_cuenta = (select c.id_cuenta from cuentas_fondos c
                                   where c.id_empresa = p.id_empresa and c.es_principal = 'S')
 where p.id_cuenta is null
/

commit
/

create or replace function fn_cuenta_fondos (
    p_id_empresa in number,
    p_id_cuenta  in number default null
) return number is
    v_id number;
begin
    if nvl(p_id_cuenta, 0) > 0 then
        select max(id_cuenta) into v_id
          from cuentas_fondos
         where id_cuenta = p_id_cuenta
           and id_empresa = p_id_empresa
           and estado = 'ACTIVO';
        if v_id is null then
            raise_application_error(-20125,
                'La caja o cuenta elegida no es de esta empresa o esta INACTIVA.');
        end if;
        return v_id;
    end if;

    select max(id_cuenta) into v_id
      from cuentas_fondos
     where id_empresa = p_id_empresa
       and es_principal = 'S'
       and estado = 'ACTIVO';
    if v_id is null then
        raise_application_error(-20125,
            'La empresa no tiene una caja principal activa. Creala en Cajas y bancos.');
    end if;
    return v_id;
end fn_cuenta_fondos;
