        update pagos set conciliado = case when upper(nvl(p_conciliado, 'N')) = 'S' then 'S' else 'N' end,
               fecha_conciliacion = case when upper(nvl(p_conciliado, 'N')) = 'S'
                                         then trunc(sysdate) end,
