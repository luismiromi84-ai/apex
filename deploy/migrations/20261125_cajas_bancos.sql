declare
    v_n number;
begin
    select count(*) into v_n from all_tables where owner = 'WKSP_SYPEXWS' and table_name = 'CUENTAS_FONDOS';
    if v_n = 0 then
        execute immediate q'[
create table cuentas_fondos (
    id_cuenta       number generated by default on null as identity,
    id_empresa      number         not null,
    nombre          varchar2(100)  not null,
    tipo            varchar2(10)   default 'CAJA' not null,
    banco           varchar2(100),
    numero_cuenta   varchar2(40),
    cod_moneda      varchar2(3)    not null,
    es_principal    char(1)        default 'N' not null,
    estado          varchar2(10)   default 'ACTIVO' not null,
    creado_por      varchar2(100),
    fecha_creacion  date           default sysdate,
    constraint pk_cuentas_fondos primary key (id_cuenta),
    constraint fk_cuenta_empresa foreign key (id_empresa) references empresas (id_empresa),
    constraint uq_cuenta_nombre unique (id_empresa, nombre),
    constraint chk_cuenta_tipo check (tipo in ('CAJA', 'BANCO')),
    constraint chk_cuenta_principal check (es_principal in ('S', 'N')),
    constraint chk_cuenta_estado check (estado in ('ACTIVO', 'INACTIVO'))
)]';
        execute immediate 'create unique index ux_cuenta_principal on cuentas_fondos '
                       || '(case when es_principal = ''S'' then id_empresa end)';
    end if;

    for t in (select 'RECIBOS' tabla, 'FK_RECIBO_CUENTA' fk from dual
              union all select 'PAGOS', 'FK_PAGO_CUENTA' from dual) loop
        select count(*) into v_n from all_tab_columns
         where owner = 'WKSP_SYPEXWS' and table_name = t.tabla and column_name = 'ID_CUENTA';
        if v_n = 0 then
            execute immediate 'alter table ' || t.tabla || ' add (id_cuenta number)';
            execute immediate 'alter table ' || t.tabla || ' add constraint ' || t.fk
                           || ' foreign key (id_cuenta) references cuentas_fondos (id_cuenta)';
            execute immediate 'create index ix_' || lower(t.tabla) || '_cuenta on ' || t.tabla || ' (id_cuenta)';
        end if;
    end loop;
end;
