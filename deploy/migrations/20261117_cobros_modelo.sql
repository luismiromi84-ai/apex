-- =============================================================================
-- 20261117_cobros_modelo.sql
--
-- Modelo de la fase de cobros (2026-11-17). Idempotente.
--
-- Que hace:
--   1. FACTURAS admite el estado PARCIAL (una factura semicolocada).
--   2. EMPRESAS gana ES_SPE: solo una empresa Sujeto Pasivo Especial cobra IGTF.
--   3. IMPUESTOS gana APLICA_EN y el IGTF de Venezuela pasa a 'CABECERA': su
--      alicuota se lee de ahi, pero deja de ofrecerse en las lineas.
--   4. FORMA_PAGO gana GENERA_IGTF (marcada en DIVISAS).
--   5. Crea RECIBOS (un cobro por factura; varios por factura para abonos).
--
-- Reversa: drop table recibos; volver el CHECK de FACTURAS a los 5 estados;
-- drop column es_spe, aplica_en, genera_igtf. Los importes ya guardados no se tocan.
--
-- Ojo: los `alter` de arriba son idempotentes, pero **el `create table` es de una
-- sola vez** (como en las demás migraciones de la casa): si se corta a medias,
-- volver a correrlo falla con ORA-00955 y hay que terminar a mano lo que falte
-- (índices y comentarios).
--
-- Verificacion: deploy/diagnostico/20261117_cobros_modelo_verificacion.sql
-- =============================================================================

alter session set current_schema = WKSP_SYPEXWS
/

declare
    v_n number;

    procedure ignora(p_sql varchar2) is
    begin
        execute immediate p_sql;
    exception
        when others then null;
    end;
begin
    -- 1. El estado PARCIAL (se rehace el CHECK siempre: es idempotente)
    ignora('alter table facturas drop constraint chk_factura_estado');
    execute immediate 'alter table facturas add constraint chk_factura_estado '
                   || 'check (estado in (''PENDIENTE'', ''TIMBRADA'', ''PARCIAL'', '
                   || '''PAGADA'', ''ANULADA'', ''FACTURADO''))';

    -- 2. La empresa como Sujeto Pasivo Especial
    select count(*) into v_n from all_tab_columns
     where owner = 'WKSP_SYPEXWS' and table_name = 'EMPRESAS' and column_name = 'ES_SPE';
    if v_n = 0 then
        execute immediate 'alter table empresas add (es_spe char(1) default ''N'')';
    end if;
    ignora('alter table empresas drop constraint chk_empresas_spe');
    execute immediate 'alter table empresas add constraint chk_empresas_spe check (es_spe in (''S'', ''N''))';

    -- 3. La alicuota del IGTF: configurada, y fuera de las lineas
    select count(*) into v_n from all_tab_columns
     where owner = 'WKSP_SYPEXWS' and table_name = 'IMPUESTOS' and column_name = 'APLICA_EN';
    if v_n = 0 then
        execute immediate 'alter table impuestos add (aplica_en varchar2(10) default ''LINEA'')';
    end if;
    ignora('alter table impuestos drop constraint chk_impuestos_aplica_en');
    execute immediate 'alter table impuestos add constraint chk_impuestos_aplica_en '
                   || 'check (aplica_en in (''LINEA'', ''CABECERA''))';
    execute immediate 'update impuestos set aplica_en = ''CABECERA''
                        where cod_impuesto = ''IGTF'' and cod_pais = ''VE''';

    -- 4. Formas de pago que declaran pago en divisas
    select count(*) into v_n from all_tab_columns
     where owner = 'WKSP_SYPEXWS' and table_name = 'FORMA_PAGO' and column_name = 'GENERA_IGTF';
    if v_n = 0 then
        execute immediate 'alter table forma_pago add (genera_igtf char(1) default ''N'')';
    end if;
    ignora('alter table forma_pago drop constraint chk_forma_pago_igtf');
    execute immediate 'alter table forma_pago add constraint chk_forma_pago_igtf check (genera_igtf in (''S'', ''N''))';
    execute immediate 'update forma_pago set genera_igtf = ''S'' where codigo = ''DIVISAS''';
end;
/

-- 5. Los recibos
create table recibos (
    id_recibo                  number generated by default as identity
                               minvalue 1 maxvalue 9999999999999999999999999999
                               increment by 1 start with 1 cache 20 noorder nocycle nokeep noscale
                               not null enable,
    id_empresa                 number not null enable,
    id_factura                 number not null enable,
    fecha_cobro                date not null enable,
    id_forma_pago              number,
    cod_moneda                 varchar2(3) not null enable,
    tipo_cambio                number(14,6) default 1 not null enable,
    monto_cobrado              number(18,2) not null enable,
    monto_bs                   number(18,2) not null enable,
    monto_factura              number(18,2) not null enable,
    aplica_igtf                char(1) default 'N' not null enable,
    igtf_monto                 number(18,2) default 0 not null enable,
    igtf_bs                    number(18,2) default 0 not null enable,
    retencion_iva_bs           number(18,2) default 0 not null enable,
    nro_comprobante_retencion  varchar2(14),
    monto_neto                 number(18,2) not null enable,
    referencia                 varchar2(60),
    conciliado                 char(1) default 'N' not null enable,
    fecha_conciliacion         date,
    estado                     varchar2(10) default 'ACTIVO' not null enable,
    observaciones              varchar2(4000),
    creado_por                 varchar2(100) default user,
    fecha_creacion             timestamp(6) default systimestamp not null enable,
    modificado_por             varchar2(100),
    fecha_modificacion         timestamp(6),
    constraint pk_recibos primary key (id_recibo) using index enable,
    constraint fk_recibos_empresa foreign key (id_empresa) references empresas (id_empresa) enable,
    constraint fk_recibos_factura foreign key (id_factura) references facturas (id_factura) enable,
    constraint fk_recibos_forma_pago foreign key (id_forma_pago) references forma_pago (id_forma_pago) enable,
    constraint chk_recibos_estado check (estado in ('ACTIVO', 'ANULADO')) enable,
    constraint chk_recibos_igtf check (aplica_igtf in ('S', 'N')) enable,
    constraint chk_recibos_conciliado check (conciliado in ('S', 'N')) enable,
    constraint chk_recibos_montos check (monto_cobrado > 0) enable,
    constraint chk_recibos_comprobante check (nro_comprobante_retencion is null
                                              or regexp_like(nro_comprobante_retencion, '^[0-9]{14}$')) enable
)
/

create index ix_recibos_factura on recibos (id_factura)
/
create index ix_recibos_empresa_fecha on recibos (id_empresa, fecha_cobro)
/

comment on table recibos is 'Cobros (totales o abonos) de una factura; el IGTF no es ingreso'
/
comment on column recibos.monto_factura is 'Equivalente en la moneda de la factura, con la tasa del dia del cobro'
/
comment on column recibos.monto_neto is 'Dinero que entra al banco: bruto - retencion + IGTF'
/
comment on column recibos.igtf_bs is 'IGTF percibido en bolivares: impuesto por enterar, no ingreso'
/

begin
    dbms_utility.compile_schema('WKSP_SYPEXWS', false);
end;
/
