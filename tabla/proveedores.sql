-- =============================================================================
-- tabla/proveedores.sql
--
-- Maestra de proveedores: espejo de CLIENTES para el lado de las compras.
--
-- POR QUE EXISTE: el libro de compras es un registro fiscal obligatorio y no se
-- puede armar sin la contraparte de cada factura de proveedor (RIF y razon
-- social). CLIENTES no sirve: un cliente puede ser proveedor y viceversa, y
-- mezclarlos rompe la unicidad del RIF por empresa en cada papel.
--
-- RETENER_IVA / PORCENTAJE_RETENCION: si somos agente de retencion, al registrar
-- la factura retenemos el IVA. El porcentaje por defecto es 75 % (proveedor
-- domiciliado) y se cambia a 100 % cuando el proveedor es de otro pais; 0 % lo
-- desactiva. El porcentaje es editable por factura.
--
-- No se borran: se inactivan (ESTADO = 'INACTIVO'), igual que los usuarios.
-- =============================================================================

create table proveedores (
    id_proveedor         number generated by default on null as identity
                         minvalue 1 maxvalue 9999999999999999999999999999
                         increment by 1 cache 20 noorder nocycle nokeep noscale
                         not null enable,
    id_empresa           number        not null enable,
    rif                  varchar2(30)  not null enable,
    razon_social         varchar2(150) not null enable,
    tipo_persona         char(1)       default 'J' not null enable,
    cod_pais             char(2),
    email                varchar2(100),
    telefono             varchar2(50),
    direccion            varchar2(300),
    estado               varchar2(10)  default 'ACTIVO',
    retener_iva          char(1)       default 'S' not null enable,
    porcentaje_retencion number(5,2)   default 75 not null enable,
    es_spe               char(1)       default 'N' not null enable,
    dias_credito         number(3)     default 0 not null enable,
    id_concepto_islr     number,
    fecha_creacion       date          default sysdate,
    constraint pk_proveedores primary key (id_proveedor)
        using index enable,
    constraint uq_proveedores_rif unique (id_empresa, rif)
        using index enable,
    constraint fk_proveedores_empresa foreign key (id_empresa)
        references empresas (id_empresa) enable,
    constraint fk_proveedores_pais foreign key (cod_pais)
        references paises (cod_pais) enable,
    constraint fk_proveedores_islr foreign key (id_concepto_islr)
        references islr_conceptos (id_concepto) enable,
    constraint chk_proveedores_estado check (estado in ('ACTIVO','INACTIVO')) enable,
    constraint chk_proveedores_persona check (tipo_persona in ('J','N')) enable,
    constraint chk_proveedores_retiene check (retener_iva in ('S','N')) enable,
    constraint chk_proveedores_pct check (porcentaje_retencion between 0 and 100) enable,
    constraint chk_proveedores_spe check (es_spe in ('S','N')) enable,
    constraint chk_proveedores_credito check (dias_credito between 0 and 365) enable
);

create index ix_proveedores_empresa on proveedores (id_empresa);

comment on column proveedores.rif is 'RIF (Venezuela) o RFC (Mexico) del proveedor; texto libre si es de un tercer pais';
comment on column proveedores.retener_iva is 'S = al registrar sus facturas se le retiene IVA; N = no se retiene';
comment on column proveedores.porcentaje_retencion is 'Porcentaje de IVA a retener: 75 domiciliado, 100 no domiciliado, 0 desactiva';
comment on column proveedores.es_spe is 'S = Sujeto Pasivo Especial: sus pagos en divisa causan IGTF';
comment on column proveedores.dias_credito is 'Dias de credito con los que factura el proveedor (vencimiento)';
comment on column proveedores.id_concepto_islr is 'Concepto de ISLR con el que se retiene por defecto; nulo = no se le retiene ISLR';
