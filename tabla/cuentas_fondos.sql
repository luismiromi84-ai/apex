-- =============================================================================
-- cuentas_fondos.sql
--
-- Cajas y cuentas bancarias de cada empresa (2026-11-25). Un cobro dice a que
-- cuenta ENTRA el dinero (RECIBOS.ID_CUENTA) y un pago de que cuenta SALE
-- (PAGOS.ID_CUENTA). Cada empresa tiene una cuenta PRINCIPAL (la «Caja
-- principal»), que es la que se propone por defecto. Base de la conciliacion.
-- =============================================================================

-- saldo_inicial (2026-11-26): lo que tenia la cuenta antes del primer cobro o pago en Synpex,
-- en su moneda; la primera conciliacion arranca con el.
create table cuentas_fondos (
    id_cuenta       number generated by default on null as identity,
    id_empresa      number         not null,
    nombre          varchar2(100)  not null,
    tipo            varchar2(10)   default 'CAJA' not null,
    banco           varchar2(100),
    numero_cuenta   varchar2(40),
    cod_moneda      varchar2(3)    not null,
    es_principal    char(1)        default 'N' not null,
    estado          varchar2(10)   default 'ACTIVO' not null,
    creado_por      varchar2(100),
    fecha_creacion  date           default sysdate,
    id_cuenta_ctb   number,
    saldo_inicial        number(18,2)  default 0 not null,
    fecha_saldo_inicial  date,
    constraint pk_cuentas_fondos primary key (id_cuenta),
    constraint fk_cuenta_empresa foreign key (id_empresa) references empresas (id_empresa),
    constraint uq_cuenta_nombre unique (id_empresa, nombre),
    constraint chk_cuenta_tipo check (tipo in ('CAJA', 'BANCO')),
    constraint chk_cuenta_principal check (es_principal in ('S', 'N')),
    constraint chk_cuenta_estado check (estado in ('ACTIVO', 'INACTIVO')),
    constraint fk_cuenta_ctb foreign key (id_cuenta_ctb) references ctb_cuentas (id_cuenta_ctb)
);

-- Una sola cuenta principal por empresa.
create unique index ux_cuenta_principal
    on cuentas_fondos (case when es_principal = 'S' then id_empresa end);
