-- =============================================================================
-- KARDEX_MOV
--
-- El movimiento de inventario: la verdad historica (2026-11-24). Una fila por
-- entrada o salida, con el costo aplicado, la tasa del documento y el documento
-- que la origino.
--
-- Reglas:
--   * NUNCA se edita ni se borra. Se revierte con otro movimiento numerado
--     (REVERSA_ENTRADA / REVERSA_SALIDA) que apunta al original.
--   * CANTIDAD va SIEMPRE en positivo; el sentido lo da TIPO_MOVIMIENTO.
--   * La valoracion se congela: COSTO_UNIT_BS / COSTO_TOTAL_BS en bolivares a
--     la tasa del documento, y COSTO_UNIT_REF / COSTO_TOTAL_REF en la divisa del
--     documento a ESA MISMA tasa. Asi el historico no se mueve si la tabla de
--     tasas se republica.
--   * NUM_MOVIMIENTO sale de FOLIO_CONTADOR (serie KARDEX, 'K-000001').
--
-- La escribe PKG_INVENTARIO; nadie mas.
-- =============================================================================

CREATE TABLE "KARDEX_MOV"
 (	"ID_MOVIMIENTO" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL ENABLE,
	"ID_EMPRESA" NUMBER NOT NULL ENABLE,
	"NUM_MOVIMIENTO" VARCHAR2(20) NOT NULL ENABLE,
	"ID_PRODUCTO_SERVICIO" NUMBER NOT NULL ENABLE,
	"FECHA_MOVIMIENTO" DATE NOT NULL ENABLE,
	"TIPO_MOVIMIENTO" VARCHAR2(20) NOT NULL ENABLE,
	"CANTIDAD" NUMBER(14,4) NOT NULL ENABLE,
	"COSTO_UNIT_BS" NUMBER(18,6) NOT NULL ENABLE,
	"COSTO_TOTAL_BS" NUMBER(18,2) NOT NULL ENABLE,
	"TASA_CAMBIO" NUMBER(14,6) DEFAULT 1 NOT NULL ENABLE,
	"MONEDA_DOCUMENTO" VARCHAR2(10) DEFAULT 'VES' NOT NULL ENABLE,
	"COSTO_UNIT_REF" NUMBER(18,6) DEFAULT 0 NOT NULL ENABLE,
	"COSTO_TOTAL_REF" NUMBER(18,2) DEFAULT 0 NOT NULL ENABLE,
	"DOC_TIPO" VARCHAR2(20),
	"ID_DOC" NUMBER,
	"ID_DETALLE_ORIGEN" NUMBER,
	"ID_MOVIMIENTO_REVERSA" NUMBER,
	"MOTIVO" VARCHAR2(300),
	"CREADO_POR" VARCHAR2(100) DEFAULT USER,
	"CREADO_EL" TIMESTAMP(6) DEFAULT SYSTIMESTAMP,
	 CONSTRAINT "PK_KARDEX_MOV" PRIMARY KEY ("ID_MOVIMIENTO")
  USING INDEX ENABLE,
	 CONSTRAINT "FK_KARDEX_MOV_EMPRESA" FOREIGN KEY ("ID_EMPRESA")
	  REFERENCES "EMPRESAS" ("ID_EMPRESA") ENABLE,
	 CONSTRAINT "FK_KARDEX_MOV_PRODUCTO" FOREIGN KEY ("ID_PRODUCTO_SERVICIO")
	  REFERENCES "PRODUCTO_SERVICIO" ("ID_PRODUCTO_SERVICIO") ENABLE,
	 CONSTRAINT "FK_KARDEX_MOV_REVERSA" FOREIGN KEY ("ID_MOVIMIENTO_REVERSA")
	  REFERENCES "KARDEX_MOV" ("ID_MOVIMIENTO") ENABLE,
	 CONSTRAINT "UQ_KARDEX_MOV_NUM" UNIQUE ("ID_EMPRESA", "NUM_MOVIMIENTO")
  USING INDEX ENABLE,
	 CONSTRAINT "UQ_KARDEX_MOV_REV" UNIQUE ("ID_MOVIMIENTO_REVERSA")
  USING INDEX ENABLE,
	 CONSTRAINT "CK_KARDEX_MOV_TIPO" CHECK (TIPO_MOVIMIENTO IN
	          ('ENTRADA_COMPRA', 'SALIDA_FACTURA', 'ENTRADA_NC_CLIENTE',
	           'SALIDA_ND_CLIENTE', 'SALIDA_NC_PROVEEDOR', 'ENTRADA_ND_PROVEEDOR',
	           'AJUSTE_ENTRADA', 'AJUSTE_SALIDA', 'SALDO_INICIAL',
	           'REVERSA_ENTRADA', 'REVERSA_SALIDA')) ENABLE,
	 CONSTRAINT "CK_KARDEX_MOV_CANT" CHECK (CANTIDAD > 0) ENABLE
  ) ;

CREATE INDEX "IX_KARDEX_MOV_ARTICULO" ON "KARDEX_MOV"
  ("ID_EMPRESA", "ID_PRODUCTO_SERVICIO", "FECHA_MOVIMIENTO", "ID_MOVIMIENTO") ;

CREATE INDEX "IX_KARDEX_MOV_DOC" ON "KARDEX_MOV" ("ID_EMPRESA", "DOC_TIPO", "ID_DOC") ;
