	"CONDICION_PAGO" VARCHAR2(50), 
	"COD_MONEDA" VARCHAR2(5) DEFAULT 'USD' NOT NULL ENABLE, 
	"TIPO_CAMBIO" NUMBER(12,4) DEFAULT 1 NOT NULL ENABLE, 
	"FECHA_EMISION" DATE DEFAULT SYSDATE NOT NULL ENABLE, 
	"FECHA_VENCIMIENTO" DATE, 
