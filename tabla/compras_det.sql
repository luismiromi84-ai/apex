-- =============================================================================
-- tabla/compras_det.sql
--
-- Lineas de la factura de compra. Espejo de FACTURAS_DET (mismos tipos y mismos
-- calculos en bolivares) con dos diferencias:
--
--   1. La FK a COMPRAS va SIN cascada: una compra no se borra, se anula, y si
--      tuviera lineas el borrado en cascada se las llevaria sin rastro.
--   2. ID_DETALLE_ORIGEN enlaza la linea de una nota con la linea exacta de la
--      factura que acredita, igual que en facturacion.
--
-- Los totales de la cabecera los mantiene TRG_ACTUALIZA_TOTALES_COMPRA.
-- =============================================================================

create table compras_det (
    id_detalle            number generated by default on null as identity
                          minvalue 1 maxvalue 9999999999999999999999999999
                          increment by 1 cache 20 noorder nocycle nokeep noscale
                          not null enable,
    id_compra             number        not null enable,
    num_linea             number(4,0)   not null enable,
    id_producto_servicio  number,
    descripcion           varchar2(500) not null enable,
    cantidad              number(12,4)  default 1 not null enable,
    precio_unitario       number(14,4)  default 0 not null enable,
    porcentaje_descuento  number(5,2)   default 0,
    monto_descuento       number(14,2)  default 0,
    id_impuesto           number,
    porcentaje_impuesto   number(5,2)   default 16 not null enable,
    monto_impuesto        number(14,2)  default 0 not null enable,
    subtotal_linea        number(14,2)  default 0 not null enable,
    total_linea           number(14,2)  default 0 not null enable,
    tasa_cambio_aplicada  number(14,6)  default 1 not null enable,
    subtotal_bs           number(14,2)  default 0 not null enable,
    total_bs              number(14,2)  default 0 not null enable,
    id_detalle_origen     number,
    creado_por            varchar2(100) default user,
    fecha_creacion        timestamp     default systimestamp not null enable,
    constraint pk_compras_det primary key (id_detalle)
        using index enable,
    constraint uk_compra_linea unique (id_compra, num_linea)
        using index enable,
    constraint fk_compra_det_compra foreign key (id_compra)
        references compras (id_compra) enable,
    constraint fk_compra_det_producto foreign key (id_producto_servicio)
        references producto_servicio (id_producto_servicio) enable,
    constraint fk_compra_det_impuesto foreign key (id_impuesto)
        references impuestos (id_impuesto) enable,
    constraint fk_compra_det_origen foreign key (id_detalle_origen)
        references compras_det (id_detalle) enable
);

create index ix_compras_det_compra on compras_det (id_compra);
create index ix_compras_det_origen on compras_det (id_detalle_origen);

comment on column compras_det.subtotal_bs is 'Subtotal de la linea en bolivares';
comment on column compras_det.total_bs is 'Total de la linea en bolivares (subtotal - descuento + IVA)';
comment on column compras_det.id_detalle_origen is 'Linea de la factura de compra que acredita esta nota';
