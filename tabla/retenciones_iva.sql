-- =============================================================================
-- tabla/retenciones_iva.sql
--
-- El comprobante de retencion de IVA: una fila por factura de compra (1:1).
--
-- POR QUE ES UNA TABLA APARTE Y NO UNAS COLUMNAS DE COMPRAS: el comprobante es
-- un documento fiscal propio, con numeracion consecutiva, periodo y fecha
-- propios, que se entrega al proveedor y que el SENIAT audita por separado.
-- Guarda ademas la foto de base e IVA al momento de emitirlo: si la compra se
-- corrigiera, el papel entregado no puede cambiar.
--
-- NUMERO_COMPROBANTE: 14 caracteres AAAAMM + 8 digitos secuenciales. El AAAAMM
-- es el mes en que se emite el comprobante (no el de la factura); el periodo
-- fiscal de la factura va en PERIODO_ANIO / PERIODO_MES.
-- =============================================================================

create table retenciones_iva (
    id_retencion         number generated by default on null as identity
                         minvalue 1 maxvalue 9999999999999999999999999999
                         increment by 1 cache 20 noorder nocycle nokeep noscale
                         not null enable,
    id_empresa           number        not null enable,
    id_compra            number        not null enable,
    numero_comprobante   varchar2(14)  not null enable,
    fecha_emision        date          default sysdate not null enable,
    periodo_anio         number(4)     not null enable,
    periodo_mes          number(2)     not null enable,
    base_imponible_bs    number(14,2)  default 0 not null enable,
    iva_causado_bs       number(14,2)  default 0 not null enable,
    porcentaje_retencion number(5,2)   not null enable,
    iva_retenido_bs      number(14,2)  default 0 not null enable,
    estado               varchar2(10)  default 'EMITIDO' not null enable,
    creado_por           varchar2(100) default user,
    fecha_creacion       timestamp     default systimestamp not null enable,
    constraint pk_retenciones_iva primary key (id_retencion)
        using index enable,
    constraint uq_ret_compra unique (id_compra)
        using index enable,
    constraint uq_ret_numero unique (id_empresa, numero_comprobante)
        using index enable,
    constraint fk_ret_empresa foreign key (id_empresa)
        references empresas (id_empresa) enable,
    constraint fk_ret_compra foreign key (id_compra)
        references compras (id_compra) enable,
    constraint chk_ret_estado check (estado in ('EMITIDO','ANULADO')) enable,
    constraint chk_ret_mes check (periodo_mes between 1 and 12) enable,
    constraint chk_ret_pct check (porcentaje_retencion between 0 and 100) enable
);

create index ix_retenciones_empresa on retenciones_iva (id_empresa);

comment on column retenciones_iva.numero_comprobante is 'AAAAMM + 8 digitos secuenciales; el AAAAMM es el mes de emision';
comment on column retenciones_iva.base_imponible_bs is 'Base de las lineas con IVA mayor que cero (sin exento ni IGTF)';
comment on column retenciones_iva.iva_retenido_bs is 'IVA causado por el porcentaje de retencion, redondeado a 2 decimales';
