-- =============================================================================
-- tabla/islr_conceptos.sql
--
-- Catalogo oficial de conceptos de retencion de ISLR (impuesto sobre la renta).
--
-- POR QUE EXISTE: el comprobante de ISLR no es un porcentaje tecleado; el papel
-- exige el CODIGO de concepto del SENIAT, la actividad, la tarifa y el
-- sustraendo en unidades tributarias. Sin el catalogo no se puede calcular ni
-- imprimir, y una tarifa mal puesta es dinero mal retenido.
--
-- UNA FILA POR CODIGO, no por concepto: la tabla oficial (Decreto 1.808, G.O.
-- 43.140, UT = 43 Bs) trae varias variantes del mismo concepto (natural o
-- juridica, domiciliada o no) y cada una tiene su codigo y su tarifa, asi que
-- la llave es el codigo.
--
-- BASE_PCT es la «base imponible» de la tabla: el porcentaje del monto que queda
-- sujeto (100 casi siempre, 90 en honorarios de personas naturales, 30 en primas
-- de seguro). SUSTRAENDO_UT va con 4 decimales porque la tabla imprime el
-- sustraendo en bolivares y hay que poder volver a la UT exacta (35,83 / 43 =
-- 0,8333; guardar 0,83 daria 35,69).
--
-- Las tarifas progresivas (Tarifa N° 2) y las que no son un porcentaje plano
-- (primas de seguro, tarjetas de credito) se siembran con ACTIVO = 'N': se ven
-- en el catalogo pero no se pueden elegir.
-- =============================================================================

create table islr_conceptos (
    id_concepto   number generated by default on null as identity
                  minvalue 1 maxvalue 9999999999999999999999999999
                  increment by 1 cache 20 noorder nocycle nokeep noscale
                  not null enable,
    codigo        varchar2(5)   not null enable,
    numeral       varchar2(10),
    descripcion   varchar2(200) not null enable,
    actividad     varchar2(200) not null enable,
    base_pct      number(5,2)   default 100 not null enable,
    tarifa        number(5,2)   not null enable,
    sustraendo_ut number(10,4)  default 0 not null enable,
    tipo_persona  char(1),
    domiciliado   char(1),
    activo        char(1)       default 'S' not null enable,
    constraint pk_islr_conceptos primary key (id_concepto)
        using index enable,
    constraint uq_islr_conceptos_codigo unique (codigo)
        using index enable,
    constraint chk_islr_activo check (activo in ('S','N')) enable,
    constraint chk_islr_persona check (tipo_persona in ('J','N')) enable,
    constraint chk_islr_domicilio check (domiciliado in ('S','N')) enable,
    constraint chk_islr_base check (base_pct between 0 and 100) enable,
    constraint chk_islr_tarifa check (tarifa between 0 and 100) enable
);

comment on table islr_conceptos is 'Conceptos de retencion de ISLR de la tabla oficial del SENIAT (Decreto 1.808); una fila por codigo';
comment on column islr_conceptos.codigo is 'Codigo SENIAT del concepto (002, 053, 057...); es la llave del catalogo';
comment on column islr_conceptos.numeral is 'Numeral del articulo 9 del reglamento; informativo';
comment on column islr_conceptos.actividad is 'Descripcion de la actividad que imprime el comprobante';
comment on column islr_conceptos.base_pct is 'Porcentaje del monto del documento que queda sujeto a retencion (100, 90, 30...)';
comment on column islr_conceptos.tarifa is 'Porcentaje de retencion sobre la base';
comment on column islr_conceptos.sustraendo_ut is 'Sustraendo expresado en unidades tributarias, con 4 decimales (2,5 para el 3 %; 0,8333 para el 1 %)';
comment on column islr_conceptos.activo is 'S = se puede elegir en la compra; N = solo informativo (tarifa progresiva o formula especial)';
