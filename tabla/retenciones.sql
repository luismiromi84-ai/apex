-- =============================================================================
-- tabla/retenciones.sql
--
-- Cabecera del comprobante de retencion: uno de IVA y otro de ISLR por factura de
-- compra.
--
-- POR QUE ES UNA TABLA APARTE Y NO UNAS COLUMNAS DE COMPRAS: el comprobante es
-- un documento fiscal propio, con numeracion consecutiva, periodo y fecha
-- propios, que se entrega al proveedor y que el SENIAT audita por separado.
--
-- POR QUE CABECERA + LINEAS (y no una fila plana como RETENCIONES_IVA): el
-- comprobante de IVA lleva UNA FILA POR ALICUOTA (una factura con lineas al 16 %
-- y al 8 % imprime dos), y el modelo tiene que servir tambien al ISLR. Hoy se
-- escribe una cabecera con una o varias lineas; el dia que se consoliden varias
-- facturas en un papel, las compras viviran solo en las lineas y la cabecera
-- llevara ID_COMPRA nulo (Oracle admite varios nulos en un indice unico).
--
-- LA FOTO DEL CALCULO VA EN LA LINEA (base %, tarifa, sustraendo en UT, valor de
-- la UT y sustraendo en bolivares), no aqui: es lo que permite reimprimir sin
-- recalcular y sin volver a mirar el catalogo ni la UT vigente.
--
-- NUMERO_COMPROBANTE: 14 caracteres AAAAMM + 8 digitos secuenciales, de la serie
-- unica de RETENCION_CONTADOR. El AAAAMM es el mes en que se emite el
-- comprobante (no el de la factura); el periodo fiscal de la factura va en
-- PERIODO_ANIO / PERIODO_MES.
-- =============================================================================

create table retenciones (
    id_retencion           number generated by default on null as identity
                           minvalue 1 maxvalue 9999999999999999999999999999
                           increment by 1 cache 20 noorder nocycle nokeep noscale
                           not null enable,
    id_empresa             number        not null enable,
    id_proveedor           number        not null enable,
    tipo                   varchar2(10)  not null enable,
    numero_comprobante     varchar2(14)  not null enable,
    fecha_emision          date          default sysdate not null enable,
    periodo_anio           number(4)     not null enable,
    periodo_mes            number(2)     not null enable,
    id_compra              number,
    total_con_iva_bs       number(14,2)  default 0 not null enable,
    sin_derecho_credito_bs number(14,2)  default 0 not null enable,
    base_imponible_bs      number(14,2)  default 0 not null enable,
    impuesto_bs            number(14,2)  default 0 not null enable,
    retenido_bs            number(14,2)  default 0 not null enable,
    id_concepto_islr       number,
    codigo_concepto        varchar2(5),
    actividad              varchar2(200),
    estado                 varchar2(10)  default 'EMITIDO' not null enable,
    creado_por             varchar2(100) default user,
    fecha_creacion         timestamp     default systimestamp not null enable,
    constraint pk_retenciones primary key (id_retencion)
        using index enable,
    constraint uq_retenciones_numero unique (id_empresa, tipo, numero_comprobante)
        using index enable,
    constraint uq_retenciones_compra unique (id_compra, tipo)
        using index enable,
    constraint fk_retenciones_empresa foreign key (id_empresa)
        references empresas (id_empresa) enable,
    constraint fk_retenciones_proveedor foreign key (id_proveedor)
        references proveedores (id_proveedor) enable,
    constraint fk_retenciones_compra foreign key (id_compra)
        references compras (id_compra) enable,
    constraint fk_retenciones_concepto foreign key (id_concepto_islr)
        references islr_conceptos (id_concepto) enable,
    constraint chk_retenciones_tipo check (tipo in ('IVA','ISLR')) enable,
    constraint chk_retenciones_estado check (estado in ('EMITIDO','ANULADO')) enable,
    constraint chk_retenciones_mes check (periodo_mes between 1 and 12) enable
);

create index ix_ret_empresa on retenciones (id_empresa);
create index ix_ret_proveedor on retenciones (id_proveedor);

comment on table retenciones is 'Comprobantes de retencion (IVA e ISLR): cabecera con una o varias lineas';
comment on column retenciones.tipo is 'IVA = comprobante de IVA; ISLR = comprobante de impuesto sobre la renta';
comment on column retenciones.numero_comprobante is 'AAAAMM + 8 digitos secuenciales; el AAAAMM es el mes de emision';
comment on column retenciones.id_compra is 'Factura de compra que origina el comprobante; nulo cuando se consoliden varias en un papel';
comment on column retenciones.total_con_iva_bs is 'Total del documento con IVA, en bolivares (la suma de las lineas)';
comment on column retenciones.sin_derecho_credito_bs is 'Compras sin derecho a credito fiscal, en bolivares; hoy siempre 0';
comment on column retenciones.base_imponible_bs is 'Base de las lineas con IVA mayor que cero (sin exento ni IGTF), en bolivares';
comment on column retenciones.impuesto_bs is 'IVA causado del documento, en bolivares';
comment on column retenciones.retenido_bs is 'Importe retenido en bolivares (IVA causado por el porcentaje, o ISLR ya calculado)';
comment on column retenciones.codigo_concepto is 'Codigo SENIAT del concepto de ISLR que imprime la cabecera del papel';
comment on column retenciones.estado is 'EMITIDO = vigente; ANULADO = anulado con la compra, conserva su numero';
