-- =============================================================================
-- syn_reset_password_log.sql
--
-- Auditoria de los intentos de "Recuperar contrasena" desde el login (pagina 14).
-- Se escribe desde PRC_LOG_RESET_PASSWORD con transaccion autonoma, para que el
-- registro del intento sobreviva al raise_application_error del proceso.
-- No guarda contrasenas ni hashes: solo usuario/correo intentados, IP y resultado.
-- =============================================================================

create table syn_reset_password_log (
    id                number generated by default as identity,
    usuario_intentado varchar2(100) not null,
    correo_intentado  varchar2(255) not null,
    ip                varchar2(64),
    fecha             date default sysdate not null,
    resultado         varchar2(10) not null,
    constraint pk_reset_password_log primary key (id),
    constraint ck_reset_password_log_res check (resultado in ('OK', 'FALLO'))
);

create index idx_reset_password_log_fecha on syn_reset_password_log (fecha);

comment on table  syn_reset_password_log is 'Intentos de recuperacion de contrasena desde el login';
comment on column syn_reset_password_log.resultado is 'OK si se cambio la clave; FALLO si usuario/correo no coincidieron';
