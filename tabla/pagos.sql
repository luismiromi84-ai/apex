-- =============================================================================
-- tabla/pagos.sql
--
-- Cabecera de los pagos a proveedores (2026-11-21). Espejo de RECIBOS, pero del
-- lado del dinero que sale:
--
--   1. Un pago se aplica a VARIAS facturas de compra y una factura se cancela
--      con VARIOS pagos: el reparto vive en PAGOS_DETALLE.
--   2. Un pago SIN aplicaciones es un anticipo: su monto entero queda como
--      saldo a favor del proveedor.
--   3. No se borra: se ANULA (ESTADO='ANULADO') y al anularse se liberan las
--      compras que habia aplicado.
--   4. El numero del pago es ID_PAGO, como el recibo. Si algun dia se quiere
--      serie propia, se agrega a FOLIO_CONTADOR sin tocar este modelo.
--
-- MONTO va en la moneda del pago; MONTO_BS es su equivalente con TIPO_CAMBIO,
-- que se guarda en BOLIVARES POR UNIDAD (la misma convencion de todo el sistema).
-- =============================================================================

create table pagos (
    id_pago              number generated by default on null as identity
                         minvalue 1 maxvalue 9999999999999999999999999999
                         increment by 1 cache 20 noorder nocycle nokeep noscale
                         not null enable,
    id_empresa           number        not null enable,
    id_proveedor         number        not null enable,
    fecha_pago           date          default sysdate not null enable,
    cod_moneda           varchar2(3)   not null enable,
    tipo_cambio          number(14,6)  default 1 not null enable,
    monto                number(18,2)  not null enable,
    monto_bs             number(18,2)  not null enable,
    id_forma_pago        number,
    referencia           varchar2(60),
    aplica_igtf          char(1)       default 'N' not null enable,
    igtf_monto           number(18,2)  default 0 not null enable,
    igtf_bs              number(18,2)  default 0 not null enable,
    conciliado           char(1)       default 'N' not null enable,
    fecha_conciliacion   date,
    estado               varchar2(10)  default 'ACTIVO' not null enable,
    observaciones        varchar2(4000),
    creado_por           varchar2(100) default user,
    id_cuenta            number,
    id_conciliacion      number,
    fecha_creacion       timestamp(6)  default systimestamp not null enable,
    modificado_por       varchar2(100),
    fecha_modificacion   timestamp(6),
    constraint pk_pagos primary key (id_pago)
        using index enable,
    constraint fk_pagos_empresa foreign key (id_empresa)
        references empresas (id_empresa) enable,
    constraint fk_pagos_proveedor foreign key (id_proveedor)
        references proveedores (id_proveedor) enable,
    constraint fk_pagos_forma_pago foreign key (id_forma_pago)
        references forma_pago (id_forma_pago) enable,
    constraint fk_pago_cuenta foreign key (id_cuenta) references cuentas_fondos (id_cuenta) enable,
    constraint fk_pago_concil foreign key (id_conciliacion) references conciliaciones (id_conciliacion) enable,
    constraint chk_pagos_estado check (estado in ('ACTIVO','ANULADO')) enable,
    constraint chk_pagos_igtf check (aplica_igtf in ('S','N')) enable,
    constraint chk_pagos_conciliado check (conciliado in ('S','N')) enable,
    constraint chk_pagos_monto check (monto > 0) enable
);

create index ix_pagos_empresa on pagos (id_empresa, fecha_pago);
create index ix_pagos_proveedor on pagos (id_proveedor);
create index ix_pagos_estado on pagos (estado, conciliado);

comment on table pagos is 'Pagos a proveedores: cabecera. El reparto a facturas vive en pagos_detalle';
comment on column pagos.tipo_cambio is 'Bolivares por unidad de cod_moneda (misma convencion que facturas y compras)';
comment on column pagos.estado is 'ACTIVO = vale; ANULADO = no cuenta y libera sus compras';
comment on column pagos.conciliado is 'Marca manual de conciliacion bancaria; un pago conciliado no se anula sin desmarcarlo';
