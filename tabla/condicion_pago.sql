
  CREATE TABLE "CONDICION_PAGO" 
   (	"ID_CONDICION_PAGO" NUMBER NOT NULL ENABLE, 
	"CODIGO" VARCHAR2(20) NOT NULL ENABLE, 
	"DESCRIPCION" VARCHAR2(100) NOT NULL ENABLE, 
	"DIAS_CREDITO" NUMBER DEFAULT 0 NOT NULL ENABLE, 
	"ACTIVO" VARCHAR2(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT SYSDATE NOT NULL ENABLE, 
	 CONSTRAINT "CHK_CONDICION_ACTIVO" CHECK (activo IN ('Y', 'N')) ENABLE, 
	 CONSTRAINT "CHK_CONDICION_DIAS" CHECK (dias_credito >= 0) ENABLE, 
	 CONSTRAINT "PK_CONDICION_PAGO" PRIMARY KEY ("ID_CONDICION_PAGO")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UK_CONDICION_PAGO_COD" UNIQUE ("CODIGO")
  USING INDEX  ENABLE
   ) ;

  CREATE OR REPLACE EDITIONABLE TRIGGER "TRG_CONDICION_PAGO_BI" 
BEFORE INSERT ON condicion_pago
FOR EACH ROW
BEGIN
    IF :NEW.id_condicion_pago IS NULL THEN
        :NEW.id_condicion_pago := seq_condicion_pago.NEXTVAL;
    END IF;
    :NEW.codigo := UPPER(TRIM(:NEW.codigo));
END;
/
ALTER TRIGGER "TRG_CONDICION_PAGO_BI" ENABLE;