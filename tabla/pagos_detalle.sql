-- =============================================================================
-- tabla/pagos_detalle.sql
--
-- Aplicacion de un pago a una factura de compra (2026-11-21).
--
--   MONTO_APLICADO va en la MONEDA DE LA COMPRA: es lo que baja su saldo.
--   La conversion desde la moneda del pago se hace con la tasa del pago, igual
--   que pkg_cobros guarda el equivalente del cobro en la moneda de la factura.
--
--   UNIQUE (ID_PAGO, ID_COMPRA): un pago no aplica dos veces a la misma compra.
--   Para corregir, se anula el pago; no se edita el importe.
-- =============================================================================

create table pagos_detalle (
    id_pago_detalle      number generated by default on null as identity
                         minvalue 1 maxvalue 9999999999999999999999999999
                         increment by 1 cache 20 noorder nocycle nokeep noscale
                         not null enable,
    id_pago              number        not null enable,
    id_compra            number        not null enable,
    monto_aplicado       number(18,2)  not null enable,
    fecha_creacion       timestamp(6)  default systimestamp not null enable,
    constraint pk_pagos_detalle primary key (id_pago_detalle)
        using index enable,
    constraint uq_pago_compra unique (id_pago, id_compra)
        using index enable,
    constraint fk_pd_pago foreign key (id_pago)
        references pagos (id_pago) enable,
    constraint fk_pd_compra foreign key (id_compra)
        references compras (id_compra) enable,
    constraint chk_pd_monto check (monto_aplicado > 0) enable
);

create index ix_pd_compra on pagos_detalle (id_compra);

comment on column pagos_detalle.monto_aplicado is 'Importe aplicado, en la moneda de la compra';
