-- =============================================================================
-- tabla/retenciones_det.sql
--
-- Lineas del comprobante de retencion.
--
-- UNA LINEA POR ALICUOTA en el comprobante de IVA: si la factura mezcla el 16 %
-- y el 8 %, el papel lleva dos filas con su base y su impuesto cada una, que es
-- lo que espera el formulario de la Providencia y evita imprimir un «% alicuota»
-- que no representa a todas las lineas. El comprobante de ISLR lleva una sola.
--
-- AQUI VIVE LA FOTO DEL CALCULO (BASE_PCT, TARIFA, SUSTRAENDO_UT, VALOR_UT,
-- SUSTRAENDO_BS): el papel reimpreso lee estos valores guardados y no vuelve a
-- mirar el catalogo ni la UT vigente. Si manana cambia la UT, lo ya emitido no
-- se mueve.
--
-- No lleva unico propio: el unico (compra, tipo) vive en la cabecera.
-- =============================================================================

create table retenciones_det (
    id_linea               number generated by default on null as identity
                           minvalue 1 maxvalue 9999999999999999999999999999
                           increment by 1 cache 20 noorder nocycle nokeep noscale
                           not null enable,
    id_retencion           number        not null enable,
    id_compra              number        not null enable,
    fecha_factura          date,
    nro_factura            varchar2(50),
    nro_control            varchar2(30),
    tipo_documento         varchar2(10),
    nro_nota_debito        varchar2(50),
    nro_nota_credito       varchar2(50),
    nro_factura_afectada   varchar2(50),
    total_con_iva_bs       number(14,2)  default 0 not null enable,
    sin_derecho_credito_bs number(14,2)  default 0 not null enable,
    base_imponible_bs      number(14,2)  default 0 not null enable,
    porcentaje             number(5,2)   default 0 not null enable,
    impuesto_bs            number(14,2)  default 0 not null enable,
    retenido_bs            number(14,2)  default 0 not null enable,
    base_pct               number(5,2)   default 100 not null enable,
    tarifa                 number(5,2)   default 0 not null enable,
    sustraendo_ut          number(10,4)  default 0 not null enable,
    valor_ut               number(14,2)  default 0 not null enable,
    sustraendo_bs          number(14,2)  default 0 not null enable,
    constraint pk_retenciones_det primary key (id_linea)
        using index enable,
    constraint fk_retdet_retencion foreign key (id_retencion)
        references retenciones (id_retencion) enable,
    constraint fk_retdet_compra foreign key (id_compra)
        references compras (id_compra) enable,
    constraint chk_retdet_porcentaje check (porcentaje between 0 and 100) enable,
    constraint chk_retdet_base check (base_pct between 0 and 100) enable,
    constraint chk_retdet_tarifa check (tarifa between 0 and 100) enable
);

create index ix_retdet_retencion on retenciones_det (id_retencion);
create index ix_retdet_compra on retenciones_det (id_compra);

comment on table retenciones_det is 'Lineas del comprobante: una por alicuota en IVA y una por comprobante en ISLR';
comment on column retenciones_det.id_compra is 'Factura de compra de esta linea; con la consolidacion cada linea trae la suya';
comment on column retenciones_det.tipo_documento is 'Tipo de documento de la compra que respalda la linea (FAC; las notas no emiten comprobante)';
comment on column retenciones_det.total_con_iva_bs is 'Total de la linea con IVA, en bolivares (tasa del documento)';
comment on column retenciones_det.base_imponible_bs is 'Base imponible de la linea, en bolivares; el exento y el IGTF no entran';
comment on column retenciones_det.porcentaje is 'Alicuota de IVA de la linea (16, 8...), o porcentaje de retencion en ISLR';
comment on column retenciones_det.retenido_bs is 'Importe retenido de la linea, en bolivares';
comment on column retenciones_det.base_pct is 'Porcentaje del monto sujeto que se uso al calcular (foto del concepto de ISLR)';
comment on column retenciones_det.tarifa is 'Tarifa de ISLR aplicada (foto del concepto)';
comment on column retenciones_det.sustraendo_ut is 'Sustraendo en unidades tributarias con el que se calculo (foto del concepto)';
comment on column retenciones_det.valor_ut is 'Valor de la unidad tributaria en bolivares al emitir';
comment on column retenciones_det.sustraendo_bs is 'Sustraendo llevado a bolivares (sustraendo en UT por el valor de la UT)';
