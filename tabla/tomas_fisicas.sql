-- =============================================================================
-- tomas_fisicas.sql
--
-- Toma fisica de inventario (2026-11-25, fase 4 del inventario). Una toma guarda
-- la existencia del sistema de cada producto al crearla y el conteo real; al
-- APLICARLA, la diferencia contra la existencia de ese momento entra al kardex
-- como ajuste (pkg_toma_fisica). Una sola toma abierta (BORRADOR) por empresa.
-- =============================================================================

create table tomas_fisicas (
    id_toma           number generated by default on null as identity,
    id_empresa        number        not null,
    fecha             date          not null,
    estado            varchar2(10)  default 'BORRADOR' not null,
    observaciones     varchar2(400),
    creado_por        varchar2(100),
    fecha_creacion    date          default sysdate,
    aplicado_por      varchar2(100),
    fecha_aplicacion  date,
    constraint pk_tomas_fisicas primary key (id_toma),
    constraint fk_toma_empresa foreign key (id_empresa) references empresas (id_empresa),
    constraint chk_toma_estado check (estado in ('BORRADOR', 'APLICADA', 'ANULADA'))
);

create table tomas_fisicas_det (
    id_toma              number not null,
    id_producto_servicio number not null,
    existencia_sistema   number default 0 not null,
    conteo               number,
    diferencia           number,
    constraint pk_tomas_fisicas_det primary key (id_toma, id_producto_servicio),
    constraint fk_tomadet_toma foreign key (id_toma) references tomas_fisicas (id_toma),
    constraint fk_tomadet_producto foreign key (id_producto_servicio)
        references producto_servicio (id_producto_servicio),
    constraint chk_tomadet_conteo check (conteo is null or conteo >= 0)
);
