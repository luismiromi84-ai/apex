-- =============================================================================
-- ctb_contabilidad.sql
--
-- Contabilidad, fase 2 (2026-11-25): modelo de datos aprobado con las respuestas del
-- contador (documentacion/CONTABILIDAD_ALCANCE.md).
--
--   CTB_PLANTILLA_CUENTAS / CTB_PLANTILLA_MAPEO  plan de cuentas y cuentas por concepto
--                                                 por pais (VE: estructura del contador)
--   CTB_CUENTAS / CTB_MAPEO                       copia de la plantilla por empresa
--   CTB_PERIODOS                                  meses ABIERTO / CERRADO y su numeracion
--   CTB_ASIENTOS / CTB_ASIENTO_DET                asientos en moneda funcional (Bs / MXN)
--
-- Los totales de la cabecera los recalcula trg_ctb_asiento_det; las reglas (partida doble,
-- confirmado inmutable, periodo cerrado) viven en pkg_contabilidad.
-- =============================================================================

create table ctb_plantilla_cuentas (
    cod_pais    varchar2(2)   not null,
    codigo      varchar2(30)  not null,
    nombre      varchar2(150) not null,
    naturaleza  varchar2(1),
    origen      varchar2(10)  default 'CONTADOR' not null,
    constraint pk_ctb_plantilla_cuentas primary key (cod_pais, codigo),
    constraint chk_ctbpl_naturaleza check (naturaleza is null or naturaleza in ('D', 'H')),
    constraint chk_ctbpl_origen check (origen in ('CONTADOR', 'SYNPEX'))
);

create table ctb_plantilla_mapeo (
    cod_pais     varchar2(2)   not null,
    concepto     varchar2(40)  not null,
    codigo       varchar2(30)  not null,
    descripcion  varchar2(200),
    constraint pk_ctb_plantilla_mapeo primary key (cod_pais, concepto)
);

create table ctb_cuentas (
    id_cuenta_ctb         number generated by default on null as identity,
    id_empresa            number        not null,
    codigo                varchar2(30)  not null,
    nombre                varchar2(150) not null,
    nivel                 number(2)     not null,
    id_padre              number,
    tipo                  varchar2(12)  not null,
    naturaleza            varchar2(1)   not null,
    acepta_movimiento     varchar2(1)   default 'S' not null,
    estado                varchar2(10)  default 'ACTIVO' not null,
    codigo_agrupador_sat  varchar2(20),
    origen                varchar2(10)  default 'CONTADOR' not null,
    creado_por            varchar2(100),
    fecha_creacion        date          default sysdate,
    constraint pk_ctb_cuentas primary key (id_cuenta_ctb),
    constraint uq_ctb_cuentas_codigo unique (id_empresa, codigo),
    constraint fk_ctbcta_empresa foreign key (id_empresa) references empresas (id_empresa),
    constraint fk_ctbcta_padre foreign key (id_padre) references ctb_cuentas (id_cuenta_ctb),
    constraint chk_ctbcta_tipo check (tipo in ('ACTIVO', 'PASIVO', 'PATRIMONIO', 'INGRESO', 'COSTO', 'GASTO')),
    constraint chk_ctbcta_naturaleza check (naturaleza in ('D', 'H')),
    constraint chk_ctbcta_acepta check (acepta_movimiento in ('S', 'N')),
    constraint chk_ctbcta_estado check (estado in ('ACTIVO', 'INACTIVO')),
    constraint chk_ctbcta_origen check (origen in ('CONTADOR', 'SYNPEX', 'EMPRESA'))
);

create index ix_ctb_cuentas_padre on ctb_cuentas (id_padre);

create table ctb_mapeo (
    id_empresa     number        not null,
    concepto       varchar2(40)  not null,
    id_cuenta_ctb  number        not null,
    descripcion    varchar2(200),
    constraint pk_ctb_mapeo primary key (id_empresa, concepto),
    constraint fk_ctbmap_empresa foreign key (id_empresa) references empresas (id_empresa),
    constraint fk_ctbmap_cuenta foreign key (id_cuenta_ctb) references ctb_cuentas (id_cuenta_ctb)
);

create index ix_ctb_mapeo_cuenta on ctb_mapeo (id_cuenta_ctb);

create table ctb_periodos (
    id_empresa      number        not null,
    anio            number(4)     not null,
    mes             number(2)     not null,
    estado          varchar2(10)  default 'ABIERTO' not null,
    ultimo_numero   number        default 0 not null,
    cerrado_por     varchar2(100),
    fecha_cierre    date,
    constraint pk_ctb_periodos primary key (id_empresa, anio, mes),
    constraint fk_ctbper_empresa foreign key (id_empresa) references empresas (id_empresa),
    constraint chk_ctbper_mes check (mes between 1 and 12),
    constraint chk_ctbper_estado check (estado in ('ABIERTO', 'CERRADO'))
);

create table ctb_asientos (
    id_asiento           number generated by default on null as identity,
    id_empresa           number        not null,
    anio                 number(4)     not null,
    mes                  number(2)     not null,
    numero               number,
    fecha                date          not null,
    concepto             varchar2(400) not null,
    origen               varchar2(12)  default 'MANUAL' not null,
    doc_tipo             varchar2(20),
    id_doc               number,
    evento               varchar2(20),
    estado               varchar2(12)  default 'BORRADOR' not null,
    id_asiento_original  number,
    id_asiento_reverso   number,
    total_debe           number(18,2)  default 0 not null,
    total_haber          number(18,2)  default 0 not null,
    creado_por           varchar2(100),
    fecha_creacion       date          default sysdate,
    confirmado_por       varchar2(100),
    fecha_confirmacion   date,
    constraint pk_ctb_asientos primary key (id_asiento),
    constraint fk_ctbasi_empresa foreign key (id_empresa) references empresas (id_empresa),
    constraint fk_ctbasi_original foreign key (id_asiento_original) references ctb_asientos (id_asiento),
    constraint fk_ctbasi_reverso foreign key (id_asiento_reverso) references ctb_asientos (id_asiento),
    constraint uq_ctb_asientos_numero unique (id_empresa, anio, mes, numero),
    constraint chk_ctbasi_origen check (origen in ('MANUAL', 'AUTOMATICO', 'REVERSO', 'CIERRE')),
    constraint chk_ctbasi_estado check (estado in ('BORRADOR', 'CONFIRMADO', 'REVERSADO'))
);

create index ix_ctb_asientos_periodo on ctb_asientos (id_empresa, anio, mes, estado);
create index ix_ctb_asientos_original on ctb_asientos (id_asiento_original);
create index ix_ctb_asientos_reverso on ctb_asientos (id_asiento_reverso);
-- un documento genera un solo asiento automatico por evento (el lote es repetible)
create unique index uq_ctb_asientos_doc on ctb_asientos (
    case when origen = 'AUTOMATICO' then id_empresa end,
    case when origen = 'AUTOMATICO' then doc_tipo end,
    case when origen = 'AUTOMATICO' then id_doc end,
    case when origen = 'AUTOMATICO' then evento end);

create table ctb_asiento_det (
    id_det         number generated by default on null as identity,
    id_asiento     number        not null,
    linea          number        not null,
    id_cuenta_ctb  number        not null,
    descripcion    varchar2(400),
    debe           number(18,2)  default 0 not null,
    haber          number(18,2)  default 0 not null,
    cod_moneda     varchar2(3),
    monto_moneda   number(18,2),
    tasa           number,
    tercero_tipo   varchar2(1),
    id_tercero     number,
    constraint pk_ctb_asiento_det primary key (id_det),
    constraint uq_ctb_asiento_det_linea unique (id_asiento, linea),
    constraint fk_ctbdet_asiento foreign key (id_asiento) references ctb_asientos (id_asiento),
    constraint fk_ctbdet_cuenta foreign key (id_cuenta_ctb) references ctb_cuentas (id_cuenta_ctb),
    constraint chk_ctbdet_importe check (debe >= 0 and haber >= 0 and (debe = 0 or haber = 0) and debe + haber > 0),
    constraint chk_ctbdet_tercero check (tercero_tipo is null or tercero_tipo in ('C', 'P'))
);

create index ix_ctb_asiento_det_cuenta on ctb_asiento_det (id_cuenta_ctb);
