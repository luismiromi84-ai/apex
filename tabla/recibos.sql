-- =============================================================================
-- tabla/recibos.sql
--
-- RECIBOS: cada cobro que el cliente hace de una factura (2026-11-17).
--
-- Una factura puede tener varios recibos (abonos parciales). El saldo NO se
-- guarda aqui: se calcula con fn_saldo_factura.
--
-- El IGTF no es ingreso: MONTO_NETO es el dinero que entra al banco, e
-- IGTF_MONTO / IGTF_BS son un impuesto por enterar que se declara aparte.
-- Se calcula sobre la parte cobrada en divisas, solo si la empresa es SPE
-- (EMPRESAS.ES_SPE) y con la alicuota configurada en IMPUESTOS (no hay un 3 %
-- escrito en el codigo).
--
-- No se borran recibos: se anulan (ESTADO='ANULADO') y dejan de contar para el
-- saldo, conservando el rastro.
-- =============================================================================

create table recibos (
    id_recibo                  number generated by default as identity
                               minvalue 1 maxvalue 9999999999999999999999999999
                               increment by 1 start with 1 cache 20 noorder nocycle nokeep noscale
                               not null enable,
    id_empresa                 number not null enable,
    id_factura                 number not null enable,
    fecha_cobro                date not null enable,
    id_forma_pago              number,
    cod_moneda                 varchar2(3) not null enable,
    tipo_cambio                number(14,6) default 1 not null enable,
    monto_cobrado              number(18,2) not null enable,
    monto_bs                   number(18,2) not null enable,
    monto_factura              number(18,2) not null enable,
    aplica_igtf                char(1) default 'N' not null enable,
    igtf_monto                 number(18,2) default 0 not null enable,
    igtf_bs                    number(18,2) default 0 not null enable,
    retencion_iva_bs           number(18,2) default 0 not null enable,
    nro_comprobante_retencion  varchar2(14),
    monto_neto                 number(18,2) not null enable,
    referencia                 varchar2(60),
    conciliado                 char(1) default 'N' not null enable,
    fecha_conciliacion         date,
    estado                     varchar2(10) default 'ACTIVO' not null enable,
    observaciones              varchar2(4000),
    creado_por                 varchar2(100) default user,
    id_cuenta                  number,
    id_conciliacion            number,
    fecha_creacion             timestamp(6) default systimestamp not null enable,
    modificado_por             varchar2(100),
    fecha_modificacion         timestamp(6),
    constraint pk_recibos primary key (id_recibo) using index enable,
    constraint fk_recibos_empresa foreign key (id_empresa) references empresas (id_empresa) enable,
    constraint fk_recibos_factura foreign key (id_factura) references facturas (id_factura) enable,
    constraint fk_recibos_forma_pago foreign key (id_forma_pago) references forma_pago (id_forma_pago) enable,
    constraint fk_recibo_cuenta foreign key (id_cuenta) references cuentas_fondos (id_cuenta) enable,
    constraint fk_recibo_concil foreign key (id_conciliacion) references conciliaciones (id_conciliacion) enable,
    constraint chk_recibos_estado check (estado in ('ACTIVO', 'ANULADO')) enable,
    constraint chk_recibos_igtf check (aplica_igtf in ('S', 'N')) enable,
    constraint chk_recibos_conciliado check (conciliado in ('S', 'N')) enable,
    constraint chk_recibos_montos check (monto_cobrado > 0) enable,
    constraint chk_recibos_comprobante check (nro_comprobante_retencion is null
                                              or regexp_like(nro_comprobante_retencion, '^[0-9]{14}$')) enable
) ;

create index ix_recibos_factura on recibos (id_factura);
create index ix_recibos_empresa_fecha on recibos (id_empresa, fecha_cobro);

comment on table recibos is 'Cobros (totales o abonos) de una factura; el IGTF no es ingreso';
comment on column recibos.monto_factura is 'Equivalente en la moneda de la factura, con la tasa del dia del cobro';
comment on column recibos.monto_neto is 'Dinero que entra al banco: bruto - retencion + IGTF';
comment on column recibos.igtf_bs is 'IGTF percibido en bolivares: impuesto por enterar, no ingreso';
