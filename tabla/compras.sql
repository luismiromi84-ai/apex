-- =============================================================================
-- tabla/compras.sql
--
-- Cabecera de las facturas de compra (y sus notas de credito y debito).
-- Espejo de FACTURAS, con tres diferencias que importan:
--
--   1. El FOLIO_FACTURA y el NRO_CONTROL los pone EL PROVEEDOR: no hay
--      secuencia nuestra ni fn_asignar_folio. Por eso el unico es
--      (empresa, proveedor, tipo, folio): es el control de duplicados que pide
--      el libro de compras.
--   2. Hay tres estados y no cinco: BORRADOR (cabecera sin lineas todavia),
--      REGISTRADA (cerrada: es cuando se emite el comprobante de retencion) y
--      ANULADA. Una compra no se borra nunca.
--   3. RETENCION_IVA_BS se guarda al registrar, no se recalcula: es la foto que
--      tiene que coincidir con el comprobante entregado al proveedor.
--
-- Los importes (SUBTOTAL, MONTO_IMPUESTO, MONTO_TOTAL) los mantiene el trigger
-- TRG_ACTUALIZA_TOTALES_COMPRA a partir de COMPRAS_DET. No se escriben a mano.
-- =============================================================================

create table compras (
    id_compra            number generated by default on null as identity
                         minvalue 1 maxvalue 9999999999999999999999999999
                         increment by 1 cache 20 noorder nocycle nokeep noscale
                         not null enable,
    id_empresa           number        not null enable,
    id_proveedor         number        not null enable,
    tipo_documento       varchar2(10)  default 'FAC' not null enable,
    folio_factura        varchar2(50)  not null enable,
    nro_control          varchar2(30),
    fecha_emision        date          default sysdate not null enable,
    fecha_recepcion      date          default sysdate,
    cod_moneda           varchar2(5)   default 'VES' not null enable,
    tipo_cambio          number(14,6)  default 1 not null enable,
    subtotal             number(14,2)  default 0 not null enable,
    monto_impuesto       number(14,2)  default 0 not null enable,
    monto_total          number(14,2)  default 0 not null enable,
    porcentaje_retencion number(5,2)   default 0 not null enable,
    retencion_iva_bs     number(14,2)  default 0 not null enable,
    estado               varchar2(20)  default 'BORRADOR' not null enable,
    observaciones        varchar2(4000),
    id_compra_origen     number,
    creado_por           varchar2(100) default user,
    fecha_creacion       timestamp     default systimestamp not null enable,
    modificado_por       varchar2(100),
    fecha_modificacion   timestamp,
    constraint pk_compras primary key (id_compra)
        using index enable,
    constraint uq_compras_folio unique (id_empresa, id_proveedor, tipo_documento, folio_factura)
        using index enable,
    constraint fk_compras_empresa foreign key (id_empresa)
        references empresas (id_empresa) enable,
    constraint fk_compras_proveedor foreign key (id_proveedor)
        references proveedores (id_proveedor) enable,
    constraint fk_compras_origen foreign key (id_compra_origen)
        references compras (id_compra) enable,
    constraint chk_compras_tipo check (tipo_documento in ('FAC','NC','ND')) enable,
    constraint chk_compras_estado check (estado in ('BORRADOR','REGISTRADA','ANULADA')) enable,
    constraint chk_compras_pct check (porcentaje_retencion between 0 and 100) enable
);

create index ix_compras_empresa on compras (id_empresa);
create index ix_compras_proveedor on compras (id_proveedor);
create index ix_compras_fecha on compras (fecha_emision);
create index ix_compras_origen on compras (id_compra_origen);

comment on column compras.folio_factura is 'Numero de factura del proveedor (no lo genera la app)';
comment on column compras.nro_control is 'Numero de control impreso por el proveedor';
comment on column compras.tipo_cambio is 'Bolivares por unidad de la moneda del documento (misma convencion que facturas)';
comment on column compras.retencion_iva_bs is 'IVA retenido en bolivares, fijado al registrar; debe coincidir con el comprobante';
comment on column compras.estado is 'BORRADOR = editable; REGISTRADA = cerrada y con comprobante; ANULADA = no cuenta';
