
  CREATE TABLE "EMPRESAS" 
   (	"ID_EMPRESA" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"NOMBRE_EMPRESA" VARCHAR2(150) NOT NULL ENABLE, 
	"LOGO_FILENAME" VARCHAR2(255), 
	"ESTADO" VARCHAR2(20) DEFAULT 'ACTIVO', 
	"FECHA_CREACION" TIMESTAMP (6) DEFAULT SYSTIMESTAMP, 
	"RFC" VARCHAR2(20), 
	"COD_PAIS" CHAR(2) DEFAULT 'VE' NOT NULL ENABLE, 
	"TIPO_IDENT_FISCAL" VARCHAR2(10) DEFAULT 'RIF', 
	 CHECK (estado IN ('ACTIVO', 'INACTIVO')) ENABLE, 
	 CHECK (tipo_ident_fiscal IN ('RIF','RFC')) ENABLE, 
	 PRIMARY KEY ("ID_EMPRESA")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_EMPRESAS_PAIS" FOREIGN KEY ("COD_PAIS")
	  REFERENCES "PAISES" ("COD_PAIS") ENABLE
   ) ;
