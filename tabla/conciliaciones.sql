-- =============================================================================
-- conciliaciones.sql
--
-- Conciliacion bancaria (2026-11-25, opcion A del dueno). Por caja o cuenta y
-- periodo se marcan los cobros y pagos que aparecen en el extracto; el saldo segun
-- el sistema (saldo inicial + entradas marcadas - salidas marcadas, en la moneda
-- de la cuenta) tiene que cuadrar con el saldo segun el banco para cerrar.
-- RECIBOS.ID_CONCILIACION y PAGOS.ID_CONCILIACION dicen en que cierre se marco
-- cada movimiento (pkg_conciliacion).
-- =============================================================================

create table conciliaciones (
    id_conciliacion  number generated by default on null as identity,
    id_empresa       number        not null,
    id_cuenta        number        not null,
    desde            date          not null,
    hasta            date          not null,
    saldo_inicial    number        default 0 not null,
    saldo_banco      number,
    saldo_sistema    number,
    diferencia       number,
    estado           varchar2(10)  default 'ABIERTA' not null,
    observaciones    varchar2(400),
    creado_por       varchar2(100),
    fecha_creacion   date          default sysdate,
    cerrado_por      varchar2(100),
    fecha_cierre     date,
    constraint pk_conciliaciones primary key (id_conciliacion),
    constraint fk_concil_empresa foreign key (id_empresa) references empresas (id_empresa),
    constraint fk_concil_cuenta foreign key (id_cuenta) references cuentas_fondos (id_cuenta),
    constraint chk_concil_estado check (estado in ('ABIERTA', 'CERRADA', 'ANULADA')),
    constraint chk_concil_periodo check (desde <= hasta)
);
