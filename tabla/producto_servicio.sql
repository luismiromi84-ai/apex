-- =============================================================================
-- PRODUCTO_SERVICIO
--
-- Catalogo de articulos y servicios, POR EMPRESA (2026-11-23). Antes era un
-- catalogo global con UNIQUE (CODIGO) para todo el sistema; hoy cada empresa
-- lleva el suyo y el mismo codigo interno puede existir en dos empresas.
--
-- CODIGO_BARRAS: numero interno de 8 digitos (10000001, 10000002...), unico
-- dentro de la empresa, permanente y que no se reutiliza. Lo asigna el trigger
-- TRG_PRODUCTO_SERVICIO_BARRAS con fn_asignar_folio(empresa, 'ARTICULO'); la
-- serie vive en FOLIO_CONTADOR y el contador no retrocede.
--
-- La etiqueta Code 128 la arma FN_ETIQUETA_ARTICULO (apex_barcode).
-- =============================================================================

CREATE TABLE "PRODUCTO_SERVICIO"
 (	"ID_PRODUCTO_SERVICIO" NUMBER DEFAULT "WKSP_SYPEXWS"."SEQ_PRODUCTO_SERVICIO"."NEXTVAL" NOT NULL ENABLE,
	"ID_EMPRESA" NUMBER NOT NULL ENABLE,
	"CODIGO" VARCHAR2(20) NOT NULL ENABLE,
	"CODIGO_BARRAS" VARCHAR2(20) NOT NULL ENABLE,
	"NOMBRE" VARCHAR2(150) NOT NULL ENABLE,
	"DESCRIPCION" VARCHAR2(500),
	"TIPO" VARCHAR2(20) DEFAULT 'SERVICIO',
	"PRECIO_SUGERIDO" NUMBER(15,2) DEFAULT 0.00 NOT NULL ENABLE,
	"IMPUESTO_APLICABLE" NUMBER(5,2) DEFAULT 16.00 NOT NULL ENABLE,
	"ESTADO" VARCHAR2(10) DEFAULT 'ACTIVO',
	"FECHA_CREACION" DATE DEFAULT SYSDATE NOT NULL ENABLE,
	 CONSTRAINT "PK_PRODUCTO_SERVICIO" PRIMARY KEY ("ID_PRODUCTO_SERVICIO")
  USING INDEX ENABLE,
	 CONSTRAINT "FK_PRODUCTO_EMPRESA" FOREIGN KEY ("ID_EMPRESA")
	  REFERENCES "EMPRESAS" ("ID_EMPRESA") ENABLE,
	 CONSTRAINT "UQ_PRODUCTO_CODIGO" UNIQUE ("ID_EMPRESA", "CODIGO")
  USING INDEX ENABLE,
	 CONSTRAINT "UQ_PRODUCTO_BARRAS" UNIQUE ("ID_EMPRESA", "CODIGO_BARRAS")
  USING INDEX ENABLE,
	 CONSTRAINT "SYS_PRODUCTO_TIPO" CHECK (TIPO IN ('PRODUCTO', 'SERVICIO')) ENABLE,
	 CONSTRAINT "SYS_PRODUCTO_ESTADO" CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')) ENABLE
 ) ;

CREATE INDEX "IX_PRODUCTO_EMPRESA" ON "PRODUCTO_SERVICIO" ("ID_EMPRESA", "ESTADO") ;
