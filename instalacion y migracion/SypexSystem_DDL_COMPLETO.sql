create or replace PROCEDURE prc_actualizar_tasas_diarias IS
    v_response       CLOB;
    v_tasa_usd       NUMBER;
    v_tasa_eur       NUMBER;
    v_effective_date VARCHAR2(10);
    v_fecha_vigencia DATE;
BEGIN
    -- 1. Realizar la petición HTTP a la API pública de BCV Today
    v_response := apex_web_service.make_rest_request(
        p_url         => 'https://bcv.today/api/v1/rate.json',
        p_http_method => 'GET'
    );

    -- 2. Parsear el JSON recibido
    apex_json.parse(v_response);

    -- 3. Extraer los valores del JSON
    v_tasa_usd       := apex_json.get_number(p_path => 'USD');
    v_tasa_eur       := apex_json.get_number(p_path => 'EUR');
    v_effective_date := apex_json.get_varchar2(p_path => 'effective_date');

    -- Convertir la fecha string (YYYY-MM-DD) a tipo DATE
    v_fecha_vigencia := TO_DATE(v_effective_date, 'YYYY-MM-DD');

    -- 4. Registrar la tasa de USD a VES (Bolívares)
    MERGE INTO tipo_cambio target
    USING (
        SELECT 'USD' AS moneda_origen, 
               'VES' AS moneda_destino, 
               'REAL' AS tipo_tasa, 
               v_tasa_usd AS tasa_cambio, 
               v_fecha_vigencia AS fecha_vigencia
          FROM DUAL
    ) src
    ON (
        target.moneda_origen  = src.moneda_origen AND
        target.moneda_destino = src.moneda_destino AND
        target.tipo_tasa      = src.tipo_tasa AND
        target.fecha_vigencia = src.fecha_vigencia
    )
    WHEN MATCHED THEN
        UPDATE SET target.tasa_cambio = src.tasa_cambio
    WHEN NOT MATCHED THEN
        INSERT (moneda_origen, moneda_destino, tipo_tasa, tasa_cambio, fecha_vigencia)
        VALUES (src.moneda_origen, src.moneda_destino, src.tipo_tasa, src.tasa_cambio, src.fecha_vigencia);

    -- 5. Registrar la tasa de EUR a VES (Bolívares)
    MERGE INTO tipo_cambio target
    USING (
        SELECT 'EUR' AS moneda_origen, 
               'VES' AS moneda_destino, 
               'REAL' AS tipo_tasa, 
               v_tasa_eur AS tasa_cambio, 
               v_fecha_vigencia AS fecha_vigencia
          FROM DUAL
    ) src
    ON (
        target.moneda_origen  = src.moneda_origen AND
        target.moneda_destino = src.moneda_destino AND
        target.tipo_tasa      = src.tipo_tasa AND
        target.fecha_vigencia = src.fecha_vigencia
    )
    WHEN MATCHED THEN
        UPDATE SET target.tasa_cambio = src.tasa_cambio
    WHEN NOT MATCHED THEN
        INSERT (moneda_origen, moneda_destino, tipo_tasa, tasa_cambio, fecha_vigencia)
        VALUES (src.moneda_origen, src.moneda_destino, src.tipo_tasa, src.tasa_cambio, src.fecha_vigencia);

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        -- Registrar o manejar el error
        RAISE_APPLICATION_ERROR(-20006, 'Error al actualizar tasas desde BCV: ' || SQLERRM);
END prc_actualizar_tasas_diarias;
