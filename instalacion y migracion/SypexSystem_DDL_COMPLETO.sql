create or replace FUNCTION fn_autenticar_usuario (
    p_username IN VARCHAR2,
    p_password IN VARCHAR2
) RETURN BOOLEAN IS
    v_password_hash VARCHAR2(255);
    v_input_hash    VARCHAR2(255);
    v_estado        VARCHAR2(20);
BEGIN
    -- 1. Buscar usuario
    BEGIN
        SELECT password_hash, estado
          INTO v_password_hash, v_estado
          FROM usuario
         WHERE LOWER(username) = LOWER(p_username);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            APEX_UTIL.SET_CUSTOM_AUTH_STATUS(p_status => 'Usuario o contraseña incorrectos.');
            RETURN FALSE;
    END;

    -- 2. Validar si el usuario está activo
    IF UPPER(v_estado) NOT IN ('ACTIVO', 'A', '1') THEN
        APEX_UTIL.SET_CUSTOM_AUTH_STATUS(
            p_status => 'El usuario no está activo. Por favor, contacta al administrador.'
        );
        RETURN FALSE;
    END IF;

    -- 3. Generar Hash de la contraseña ingresada
    v_input_hash := sypex_hash_password(p_password);

    -- 4. Comparar
    IF v_password_hash = v_input_hash THEN
        RETURN TRUE;
    ELSE
        APEX_UTIL.SET_CUSTOM_AUTH_STATUS(p_status => 'Usuario o contraseña incorrectos.');
        RETURN FALSE;
    END IF;

EXCEPTION
    WHEN OTHERS THEN
        APEX_UTIL.SET_CUSTOM_AUTH_STATUS(p_status => 'Error al procesar la autenticación.');
        RETURN FALSE;
END fn_autenticar_usuario;
/
create or replace FUNCTION fn_clean_num (p_val IN VARCHAR2) 
RETURN NUMBER IS
    l_limpio VARCHAR2(100);
BEGIN
    IF p_val IS NULL OR TRIM(p_val) = '' THEN  
        RETURN 0;  
    END IF;

    -- 1. Eliminar cualquier carácter que no sea número, punto, coma o signo menos
    l_limpio := REGEXP_REPLACE(p_val, '[^0-9\.,-]', '');

    -- 2. Si usa la coma como decimal (formato venezolano/latino), 
    -- reemplazamos los puntos de miles por nada y la coma por punto para que TO_NUMBER lo entienda universalmente.
    -- O si viene con formato estándar con punto, lo adaptamos.
    -- Ejemplo seguro: si contiene coma, asumimos coma decimal y punto de mil.
    IF INSTR(l_limpio, ',') > 0 AND INSTR(l_limpio, '.') > 0 THEN
        -- Si tiene ambos, el que esté más a la derecha suele ser el decimal
        IF INSTR(l_limpio, ',') > INSTR(l_limpio, '.') THEN
            l_limpio := REPLACE(l_limpio, '.', ''); -- Quitar puntos de miles
            l_limpio := REPLACE(l_limpio, ',', '.'); -- Cambiar coma decimal por punto
        ELSE
            l_limpio := REPLACE(l_limpio, ',', ''); -- Quitar comas de miles
        END IF;
    ELSIF INSTR(l_limpio, ',') > 0 THEN
        -- Solo tiene coma, la convertimos a punto decimal
        l_limpio := REPLACE(l_limpio, ',', '.');
    END IF;

    -- 3. Conversión directa y limpia
    RETURN TO_NUMBER(l_limpio);
    
EXCEPTION
    WHEN OTHERS THEN
        -- Opcional: puedes registrar el error con RAISE_APPLICATION_ERROR si vuelve a fallar para depurar
        RETURN 0;
END fn_clean_num;
/
create or replace FUNCTION fn_tasa_cambio (
    p_fecha         IN DATE,
    p_moneda_origen IN VARCHAR2 DEFAULT 'USD'
) RETURN NUMBER IS
    v_tasa NUMBER(12,6);
BEGIN
    -- Si la moneda es Bolívares (VES o BS), la tasa siempre es 1 por ley y normativa
    IF p_moneda_origen IN ('VES', 'BS') THEN
        RETURN 1.0000;
    END IF;

    -- Si la fecha es nula, retorna nulo directamente
    IF p_fecha IS NULL THEN
        RETURN NULL;
    END IF;

    SELECT MAX(TASA_CAMBIO) KEEP (DENSE_RANK LAST ORDER BY FECHA_VIGENCIA ASC)
      INTO v_tasa
      FROM TIPO_CAMBIO
     WHERE MONEDA_ORIGEN = p_moneda_origen
       AND FECHA_VIGENCIA <= TRUNC(p_fecha);

    RETURN NVL(v_tasa, 1); -- Si no encuentra tasa para la divisa, por seguridad retorna 1 o puedes dejarlo en NULL
EXCEPTION
    WHEN OTHERS THEN
        RETURN 1;
END;
/
create or replace FUNCTION sypex_hash_password (
    p_password IN VARCHAR2
) RETURN VARCHAR2 IS
    v_hash VARCHAR2(255);
BEGIN
    IF p_password IS NULL THEN
        RETURN NULL;
    END IF;

    -- Usamos SQL dinámico para saltar la validación estática de PL/SQL
    EXECUTE IMMEDIATE 
        'SELECT LOWER(RAWTOHEX(STANDARD_HASH(:1, ''SHA256''))) FROM DUAL'
        INTO v_hash
        USING (p_password || 'SYPEX_SALT_2026');

    RETURN v_hash;
END sypex_hash_password;
